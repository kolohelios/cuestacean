//! Independent expectations for the narrow compiler facade, not parser semantics.
use bootstrap_executor::{ast, lowering, module};
use serde_json::{Value, json};
use std::{fs, path::Path, process::Command};

type TestResult = Result<(), Box<dyn std::error::Error>>;
const AST_CLI: &str = env!("CARGO_BIN_EXE_bootstrap-ast-codegen");
const META_CLI: &str = env!("CARGO_BIN_EXE_bootstrap-lower-codegen");
const HEADER: &str = "// Generated by bootstrap-ast-codegen. Do not edit by hand.\nuse serde_json::Value;\npub fn build(";

fn builder(parameters: Value, result: Value) -> String {
    json!({"formatVersion":1,"parameters":parameters,"result":result}).to_string()
}
fn literal(value: i64) -> String {
    builder(json!([]), json!({"op":"integer","value":value}))
}
fn policy(cases: Value) -> String {
    json!({"formatVersion":1,"cases":cases}).to_string()
}
fn constant_policy(op: &str, value: &str) -> String {
    policy(json!({op:{"op":"text","value":value}}))
}

#[test]
fn exact_ast_source_values_and_owned_final_use() -> TestResult {
    for n in [i64::MIN, 7, i64::MAX] {
        assert_eq!(ast::interpret(&literal(n), &[])?, json!(n));
        assert_eq!(
            ast::generate(&literal(n))?,
            format!("{HEADER}) -> Value {{\nValue::from({n}i64)\n}}\n")
        );
    }
    let input = builder(json!([]), json!({"op":"string","value":"\"\\\n\t雪"}));
    assert_eq!(ast::interpret(&input, &[])?, json!("\"\\\n\t雪"));
    assert_eq!(
        ast::generate(&input)?,
        format!("{HEADER}) -> Value {{\nValue::String(String::from(\"\\\"\\\\\\n\\t雪\"))\n}}\n")
    );
    let input = builder(
        json!([
            {"name":"s","type":"string"},{"name":"j","type":"json"},{"name":"n","type":"integer"}
        ]),
        json!({"op":"object","fields":[
            {"key":{"op":"argument","name":"s"},"value":{"op":"argument","name":"s"}},
            {"key":{"op":"string","value":"a"},"value":{"op":"argument","name":"j"}},
            {"key":{"op":"string","value":"b"},"value":{"op":"argument","name":"j"}},
            {"key":{"op":"string","value":"c"},"value":{"op":"argument","name":"n"}},
            {"key":{"op":"string","value":"d"},"value":{"op":"argument","name":"n"}}
        ]}),
    );
    assert_eq!(
        ast::generate(&input)?,
        format!(
            "{HEADER}_arg0: String, _arg1: Value, _arg2: i64) -> Value {{\nValue::Object(serde_json::Map::from_iter([(_arg0.clone(), Value::String(_arg0)),\n(String::from(\"a\"), _arg1.clone()),\n(String::from(\"b\"), _arg1),\n(String::from(\"c\"), Value::from(_arg2)),\n(String::from(\"d\"), Value::from(_arg2))]))\n}}\n"
        )
    );
    assert_eq!(
        ast::interpret(
            &input,
            &[json!("key"), json!([null, true]), json!(i64::MIN)]
        )?,
        json!({"key":"key","a":[null,true],"b":[null,true],"c":i64::MIN,"d":i64::MIN})
    );
    let duplicate = builder(
        json!([]),
        json!({"op":"object","fields":[
            {"key":{"op":"string","value":"x"},"value":{"op":"integer","value":1}},
            {"key":{"op":"string","value":"x"},"value":{"op":"integer","value":2}}
        ]}),
    );
    assert_eq!(ast::interpret(&duplicate, &[])?, json!({"x":2}));
    Ok(())
}

#[test]
fn typed_ast_rejection_custom_policy_and_recovery() -> TestResult {
    for (input, reason) in [
        (
            builder(json!([]), json!({"op":"argument","name":"absent"})),
            "unknown argument",
        ),
        (
            builder(
                json!([{"name":"x","type":"json"},{"name":"x","type":"json"}]),
                json!({"op":"integer","value":0}),
            ),
            "empty or duplicate parameter name",
        ),
        (
            builder(
                json!([]),
                json!({"op":"object","fields":[{"key":{"op":"integer","value":1},"value":{"op":"integer","value":2}}]}),
            ),
            "object key must be a string",
        ),
    ] {
        assert!(
            matches!(ast::generate(&input), Err(ast::Error::Program { reason: r }) if r == reason)
        );
        // Builder validation precedes even malformed custom-policy decoding.
        assert!(
            matches!(ast::generate_with_policy(&input, "{"), Err(ast::Error::Program { reason: r }) if r == reason)
        );
    }
    let input = builder(
        json!([{"name":"n","type":"integer"}]),
        json!({"op":"argument","name":"n"}),
    );
    for args in [
        vec![],
        vec![json!("1")],
        vec![json!(9223372036854775808u64)],
    ] {
        assert!(matches!(
            ast::interpret(&input, &args),
            Err(ast::Error::Arguments { .. })
        ));
    }
    assert!(matches!(ast::generate("{"), Err(ast::Error::Json { .. })));
    assert!(matches!(
        ast::generate_with_policy(&literal(7), "{"),
        Err(ast::Error::Lowering { .. })
    ));
    let forced = constant_policy("program", "pub fn independent() -> i64 { 99 }\n");
    assert_eq!(
        ast::generate_with_policy(&literal(7), &forced)?,
        "pub fn independent() -> i64 { 99 }\n"
    );
    assert_eq!(ast::interpret(&literal(7), &[])?, json!(7));
    Ok(())
}

#[test]
fn complete_meta_source_and_custom_root_control() -> TestResult {
    let input = constant_policy("x", "hello");
    let expected = concat!(
        "// Generated lowering driver. Do not edit.\n",
        "use bootstrap_executor::lowering::{self, Context, Driver, Error};\nuse serde_json::Value;\n\n",
        "pub struct Compiled;\n\nimpl Driver for Compiled {\n",
        "    fn render(&self, ctx: &mut Context, _node: &Value, _depth: usize) -> Result<String, Error> {\n",
        "        match lowering::instruction_op(_node)? {\n",
        "            \"x\" => ctx.text(\"hello\"),\n",
        "            op => Err(lowering::missing_case(op)),\n        }\n    }\n",
        "}\n\npub fn lower(node: &Value) -> Result<String, Error> {\n    Context::run(node, &Compiled)\n}\n"
    );
    assert_eq!(lowering::generate(&input)?, expected);
    let custom = constant_policy("driver", "// independent whole driver\n");
    assert_eq!(
        lowering::generate_with_policy(&input, &custom)?,
        "// independent whole driver\n"
    );
    assert!(
        lowering::generate_with_policy(&input, &constant_policy("text", "not a driver")).is_err()
    );
    assert!(lowering::generate_with_policy("{", &custom).is_err());
    Ok(())
}

#[test]
fn typed_policies_module_cursor_and_limits() -> TestResult {
    for invalid in [
        r#"{"formatVersion":1,"cases":{"x":{"op":"get","name":"unbound"}}}"#,
        r#"{"formatVersion":1,"cases":{"x":{"op":"text","value":"x"}},"aliases":{"a":"missing"}}"#,
        r#"{"formatVersion":1,"cases":{"x":{"op":"text","value":"x"}},"module":null}"#,
        r#"{"formatVersion":1,"cases":{"x":{"op":"text","value":"x"}},"module":[{"op":"moduleText","value":"x"}]}"#,
        r#"{"formatVersion":1,"cases":{"x":{"op":"text","value":"x"},"x":{"op":"text","value":"y"}}}"#,
    ] {
        assert!(lowering::Policy::parse(invalid).is_err(), "{invalid}");
        assert!(lowering::generate(invalid).is_err(), "{invalid}");
    }
    let cases = json!({"x":{"op":"string","field":"value"}});
    let rules = vec![
        ("a\"\n".into(), json!({"op":"x","value":"雪"})),
        ("b".into(), json!({"op":"x","value":"\\"})),
    ];
    let missing = lowering::Policy::parse(&policy(cases.clone()))?;
    assert_eq!(
        module::Frame::run(&rules, &missing)
            .expect_err("missing module")
            .to_string(),
        "lowering: missing module program"
    );
    let assemble = |body: Value| -> Result<String, lowering::Error> {
        let p = lowering::Policy::parse(
            &json!({"formatVersion":1,"cases":cases,"module":body}).to_string(),
        )?;
        module::Frame::run(&rules, &p)
    };
    assert_eq!(assemble(json!([]))?, "");
    assert_eq!(
        assemble(
            json!([{"op":"firstRule"},{"op":"whileRules","body":[{"op":"kind"},{"op":"expression"},{"op":"nextRule"}]}])
        )?,
        "\"a\\\"\\n\"\"雪\"\"b\"\"\\\\\""
    );
    assert_eq!(
        assemble(
            json!([{"op":"lastRule"},{"op":"whileRules","body":[{"op":"kind"},{"op":"previousRule"}]}])
        )?,
        "\"b\"\"a\\\"\\n\""
    );
    assert!(assemble(json!([{"op":"kind"}])).is_err());
    assert!(assemble(json!([{"op":"firstRule"},{"op":"whileRules","body":[]}])).is_err());
    assert_eq!(missing.lower(&json!({"op":"x","value":"\n"}))?, "\"\\n\"");
    assert!(missing.lower(&json!({"op":"x","value":1})).is_err());
    Ok(())
}

#[cfg(feature = "compiled-lowering")]
#[test]
fn fresh_compiled_drivers_execute_shared_contexts() -> TestResult {
    use bootstrap_executor::{compiled_ast_lowering, compiled_meta_lowering};
    let ast_driver = compiled_ast_lowering::Compiled;
    let meta_driver = compiled_meta_lowering::Compiled;
    assert_eq!(
        lowering::Context::run(&json!({"op":"integer","value":i64::MIN}), &ast_driver)?,
        "Value::from(-9223372036854775808i64)"
    );
    assert_eq!(
        lowering::Context::run(&json!({"op":"text","value":"hello"}), &meta_driver)?,
        "ctx.text(\"hello\")"
    );
    assert!(lowering::Context::run(&json!({"op":"integer","value":"bad"}), &ast_driver).is_err());
    assert!(lowering::Context::run(&json!({"op":"unknown"}), &meta_driver).is_err());
    assert!(module::Frame::run(&[], &meta_driver).is_err());
    Ok(())
}

#[cfg(feature = "source")]
#[test]
fn all_eight_real_builders_have_independent_json_expectations() {
    assert_eq!(
        ast::program(json!({"leaf":true})),
        json!({"formatVersion":1,"entry":{"leaf":true}})
    );
    assert_eq!(ast::atom("top".into()), json!({"kind":"top"}));
    assert_eq!(
        ast::integer("bound".into(), "floor".into(), i64::MIN),
        json!({"kind":"bound","floor":i64::MIN})
    );
    assert_eq!(
        ast::text("string".into(), "payload".into(), "\"\\\n雪".into()),
        json!({"kind":"string","payload":"\"\\\n雪"})
    );
    assert_eq!(
        ast::unary("not".into(), "child".into(), json!(true)),
        json!({"kind":"not","child":true})
    );
    assert_eq!(
        ast::binary("pair".into(), "a".into(), "b".into(), json!(1), json!(null)),
        json!({"kind":"pair","a":1,"b":null})
    );
    assert_eq!(
        ast::ternary(
            "slice".into(),
            "base".into(),
            "lo".into(),
            "hi".into(),
            json!([1]),
            json!(0),
            json!(1)
        ),
        json!({"kind":"slice","base":[1],"lo":0,"hi":1})
    );
    assert_eq!(
        ast::record_field("\"雪".into(), json!({"kind":"top"})),
        json!({"name":"\"雪","value":{"kind":"top"}})
    );
}

#[test]
fn original_clis_clear_environment_errors_and_recovery() -> TestResult {
    // Mandatory Cargo discovery above; never search PATH or treat setup as rejection.
    for binary in [AST_CLI, META_CLI] {
        assert!(Path::new(binary).is_absolute());
        assert!(fs::metadata(binary)?.is_file());
        fs::File::open(binary)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            assert_ne!(fs::metadata(binary)?.permissions().mode() & 0o111, 0);
        }
    }
    let root = std::env::temp_dir().join(format!("native-core-cli-{}", std::process::id()));
    fs::create_dir(&root)?;
    let result = cli_cases(&root);
    fs::remove_dir_all(&root)?;
    result
}

fn cli_cases(root: &Path) -> TestResult {
    let home = root.join("home");
    fs::create_dir(&home)?;
    let input = root.join("input.json");
    let custom = root.join("custom.json");
    let bad = root.join("bad.json");
    fs::write(&bad, "{")?;
    let run = |binary: &str, args: &[&Path]| {
        Command::new(binary)
            .args(args)
            .env_clear()
            .env("HOME", &home)
            .env("PATH", "/nonexistent")
            .output()
    };
    let absent = root.join("absent");
    for (binary, source, override_policy, expected) in [
        (
            AST_CLI,
            literal(7),
            constant_policy("program", "custom AST\n"),
            "custom AST\n",
        ),
        (
            META_CLI,
            constant_policy("x", "hello"),
            constant_policy("driver", "custom meta\n"),
            "custom meta\n",
        ),
    ] {
        fs::write(&input, source)?;
        fs::write(&custom, override_policy)?;
        for args in [
            vec![],
            vec![bad.as_path()],
            vec![input.as_path(), bad.as_path()],
            vec![input.as_path(), custom.as_path(), bad.as_path()],
            vec![absent.as_path()],
        ] {
            let output = run(binary, &args)?;
            assert_eq!(output.status.code(), Some(2));
            assert!(output.stdout.is_empty());
            assert!(!output.stderr.is_empty());
        }
        let typed = root.join("typed-invalid.json");
        let (invalid, diagnostic) = if binary == AST_CLI {
            (
                builder(json!([]), json!({"op":"argument","name":"absent"})),
                "unknown argument",
            )
        } else {
            (
                policy(json!({"x":{"op":"get","name":"unbound"}})),
                "unknown binding",
            )
        };
        fs::write(&typed, invalid)?;
        let output = run(binary, &[&typed])?;
        assert_eq!(output.status.code(), Some(2));
        assert!(output.stdout.is_empty());
        assert!(String::from_utf8(output.stderr)?.contains(diagnostic));
        let output = run(binary, &[&input, &custom])?;
        assert!(output.status.success());
        assert!(output.stderr.is_empty());
        assert_eq!(output.stdout, expected.as_bytes());
        let expected = if binary == AST_CLI {
            ast::generate(&fs::read_to_string(&input)?)?
        } else {
            lowering::generate(&fs::read_to_string(&input)?)?
        };
        for _ in 0..2 {
            let output = run(binary, &[&input])?;
            assert!(output.status.success());
            assert!(output.stderr.is_empty());
            assert_eq!(output.stdout, expected.as_bytes());
        }
    }
    Ok(())
}
