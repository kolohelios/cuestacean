const FOOTER: &str = "kind => Err(Error::MissingRule { kind: kind.to_string() }),\n}\n}\n";
fn expected(header: &str, footer: &str, first: &str, step: &str) -> Value {
    json!({"module":[
        {"op":"text","value":format!("{header}\n")}, {"op":first},
        {"op":"whileRules","body":[{"op":"kind"},{"op":"text","value":" => "},
            {"op":"expression"},{"op":"text","value":",\n"},{"op":step}]},
        {"op":"text","value":footer}
    ]})
}
fn baseline() -> Value {
    expected(HEADER, FOOTER, "firstRule", "nextRule")
}
fn parsed(data: &str) -> Value {
    serde_json::from_str(data).expect("complete JSON")
}
fn decoded(out: Output) -> Value {
    assert_eq!(out.status.code(), Some(0), "{out:?}");
    assert!(
        out.stderr.is_empty(),
        "successful export has no diagnostics"
    );
    serde_json::from_slice(&out.stdout).expect("complete process JSON")
}
fn executable(path: &Path) {
    assert!(path.is_absolute());
    let metadata = fs::metadata(path).expect("mandatory tool metadata");
    assert!(metadata.is_file(), "REGULAR mandatory tool");
    fs::File::open(path).expect("readable mandatory tool");
    assert_ne!(metadata.permissions().mode() & 0o111, 0);
}
fn go_failure(out: &Output, diagnostic: &str) {
    assert_eq!(out.status.code(), Some(1), "Go phase: {out:?}");
    assert!(out.stdout.is_empty(), "no partial JSON");
    assert!(
        String::from_utf8_lossy(&out.stderr).contains(diagnostic),
        "{out:?}"
    );
}
fn definition(name: &str, data: &str) -> String {
    format!("package bootstrap\n{name}: {data}\n")
}
