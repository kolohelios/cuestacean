const PACKAGE: &str = include_str!("../../native-policy-package.cue");
const HELPERS: &str = include_str!("../../scan-lowering-helpers.cue");
const FLOW: &str = include_str!("../../scan-lowering-flow.cue");
const PREDICATES: &str = include_str!("../../scan-lowering-predicates.cue");
const ADVANCE: &str = include_str!("../../scan-advance-policy.cue");
const SCHEMA: &str = include_str!("../../schema.cue");
const BRIDGE: &str = include_str!("../../scan-lowering-fragments.cue");
const SELECTOR: &str = include_str!("../../scan-lowering.cue");
const UNICODE: &str = include_str!("../../tests/valid/scan-lowering-unicode.cue");
const COMPOSE: &str = include_str!("../../compose-policy.jq");
const ASCII_STEP: &str = "cursor.step()?;\ncursor.advance()?;\n";
const UNICODE_STEP: &str = "cursor.step()?;\ncursor.advance_char()?;\n";
const FLOW_NAMES: [&str; 8] = [
    "program",
    "repeat",
    "while",
    "if",
    "advanceChar",
    "break",
    "setFlag",
    "reject",
];
const PREDICATE_NAMES: [&str; 6] = ["and", "or", "byteIn", "charIn", "flagIs", "hasByte"];

// Independently authored instruction trees from the scanner/lowering contracts.
// No provider output (including scratch feasibility captures) constructs these.
fn text(value: &str) -> Value {
    json!({"op":"text", "value":value})
}
fn field(op: &str, name: &str) -> Value {
    json!({"op":op, "field":name})
}
fn concat(parts: Vec<Value>) -> Value {
    json!({"op":"concat", "parts":parts})
}
fn branch(op: &str, name: &str, yes: Value, no: Value) -> Value {
    json!({"op":op,"field":name,"then":yes,"else":no})
}
fn equal(left: Value, right: Value, yes: Value, no: Value) -> Value {
    json!({"op":"ifEqual","left":left,"right":right,"then":yes,"else":no})
}
fn bind(name: &str, value: Value, body: Value) -> Value {
    json!({"op":"bind","name":name,"value":value,"body":body})
}
fn expected() -> [Value; 3] {
    let empty = || text("");
    let step = || text("cursor.step()?;\n");
    let get_then = || json!({"op":"get","name":"then"});
    let get_else = || json!({"op":"get","name":"else"});
    let depth = || field("unsigned", "depth");
    let body = || field("list", "body");
    let not = || branch("ifTrue", "inverse", text("!"), empty());
    let flow = json!({"formatVersion":1,"cases":{
        "program":concat(vec![
            text("// Generated by bootstrap-scan-codegen. Do not edit by hand.\nuse crate::scanner::{Cursor, Error, Scan};\npub fn scan(source: &str, offset: usize) -> Result<Scan, Error> {\nlet "),
            branch("ifEmpty","body",text("cursor"),text("mut cursor")),
            text(" = Cursor::new(source, offset)?;\n"),body(),text("Ok(cursor.finish())\n}\n")]),
        "repeat":concat(vec![step(),branch("ifZero","count",empty(),
            branch("ifTrue","once",concat(vec![
                branch("ifTrue","labeled",concat(vec![text("'scan"),depth(),text(": ")]),empty()),
                text("{\n"),step(),body(),text("}\n")]),
                concat(vec![text("for _ in 0.."),field("unsigned","count"),text(" {\n"),step(),body(),text("}\n")])))]),
        "while":branch("ifTrue","once",concat(vec![step(),text("if "),field("lower","condition"),
            text(" {\n'scan"),depth(),text(": {\n"),body(),text("}\n}\n")]),
            concat(vec![text("while { cursor.step()?; "),field("lower","condition"),text(" } {\n"),body(),text("}\n")])),
        "if":bind("then",field("list","then"),bind("else",field("list","else"),concat(vec![step(),
            equal(get_then(),get_else(),get_then(),
                equal(get_then(),empty(),concat(vec![text("if "),field("lower","inverted"),text(" {\n"),get_else(),text("}\n")]),
                    concat(vec![text("if "),field("lower","condition"),text(" {\n"),get_then(),
                        equal(get_else(),empty(),empty(),concat(vec![text("} else {\n"),get_else()])),text("}\n")])))]))),
        "advanceChar":text(UNICODE_STEP),
        "break":concat(vec![step(),branch("ifTrue","labeled",
            concat(vec![text("break 'scan"),field("unsigned","label"),text(";\n")]),text("break;\n"))]),
        "setFlag":concat(vec![step(),text("cursor.set_flag("),field("boolean","value"),text(");\n")]),
        "reject":concat(vec![step(),text("cursor.reject("),field("string","reason"),text(")?;\n")])
    }});
    let predicates = json!({"cases":{
        "and":concat(vec![text("("),field("lower","left"),branch("ifTrue","inverse",text(") || ("),text(") && (")),field("lower","right"),text(")")]),
        "or":concat(vec![text("("),field("lower","left"),branch("ifTrue","inverse",text(") && ("),text(") || (")),field("lower","right"),text(")")]),
        "byteIn":concat(vec![not(),text("matches!("),branch("ifZero","ahead",text("cursor.peek()"),
            concat(vec![text("cursor.peek_at("),field("unsigned","ahead"),text(")")])),text(", Some("),field("bytePattern","bytes"),text("))")]),
        "charIn":concat(vec![not(),text("matches!(cursor.peek_char(), Some("),field("charPattern","characters"),text("))")]),
        "flagIs":branch("ifTrue","inverse",branch("ifTrue","value",text("!cursor.flag()"),text("cursor.flag()")),
            branch("ifTrue","value",text("cursor.flag()"),text("!cursor.flag()"))),
        "hasByte":branch("ifTrue","inverse",text("cursor.peek().is_none()"),text("cursor.peek().is_some()"))
    }});
    [
        flow,
        predicates,
        json!({"cases":{"advance":text(ASCII_STEP)}}),
    ]
}
fn full_expected(modules: &[Value; 3]) -> Value {
    let mut result = json!({"formatVersion":1,"cases":{}});
    for module in modules {
        for (name, instruction) in module["cases"].as_object().expect("expected cases") {
            assert!(
                result["cases"]
                    .as_object_mut()
                    .expect("expected cases object")
                    .insert(name.clone(), instruction.clone())
                    .is_none()
            );
        }
    }
    result
}
fn parsed(output: &Output) -> Value {
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    assert!(output.stdout.len() <= 65536);
    serde_json::from_slice(&output.stdout).expect("complete bounded JSON")
}
fn failed(output: &Output) {
    assert!(!output.status.success());
    assert!(output.stdout.is_empty(), "no partial JSON");
    assert!(!output.stderr.is_empty(), "mandatory diagnostic");
}
fn encoded(output: Output) -> String {
    parsed(&output);
    String::from_utf8(output.stdout).expect("JSON UTF-8")
}
struct Probe {
    dir: PathBuf,
    native: PathBuf,
    cue: PathBuf,
    jq: PathBuf,
}
impl Probe {
    fn new() -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let dir = std::env::temp_dir().join(format!(
            "scan-policy-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        assert!(dir.is_absolute());
        fs::create_dir(&dir).expect("fresh owned scratch");
        fs::create_dir(dir.join("home")).expect("owned HOME");
        let provider = |name| {
            std::env::split_paths(&std::env::var_os("PATH").expect("pinned toolchain PATH"))
                .map(|p| p.join(name))
                .find(|p| p.is_file())
                .expect("mandatory pinned provider")
                .canonicalize()
                .expect("absolute provider")
        };
        let probe = Self {
            dir,
            native: PathBuf::from(env!("CARGO_BIN_EXE_cuestacean-spec-export")),
            cue: provider("cue"),
            jq: provider("jq"),
        };
        for binary in [&probe.native, &probe.cue, &probe.jq] {
            assert!(binary.is_absolute());
            fs::File::open(binary).expect("readable mandatory provider");
            assert_ne!(
                fs::metadata(binary)
                    .expect("provider metadata")
                    .permissions()
                    .mode()
                    & 0o111,
                0
            );
        }
        fs::write(probe.dir.join("compose-policy.jq"), COMPOSE).expect("production composer");
        probe
    }
    fn run(&self, binary: &Path, args: &[&str], inputs: &[(&str, &str)], reverse: bool) -> Output {
        let mut names = Vec::new();
        // Pass only explicit file paths, never a package/directory selector.
        for (name, source) in inputs {
            let path = self.dir.join(name);
            fs::write(&path, source).expect("fresh explicit input");
            names.push(path);
        }
        if reverse {
            names.reverse();
        }
        Command::new(binary)
            .env_clear()
            .env("PATH", "/unusable")
            .env("HOME", self.dir.join("home"))
            .current_dir(&self.dir)
            .args(args)
            .args(names)
            .output()
            .expect("mandatory process setup")
    }
    fn native(&self, companion: &str, source: &str, reverse: bool) -> String {
        let inputs = if reverse {
            [
                ("renamed-owner.cue", source),
                ("renamed-companion.cue", companion),
            ]
        } else {
            [("helpers.cue", companion), ("owner.cue", source)]
        };
        let first = self.run(&self.native, &[], &inputs, false);
        let second = self.run(&self.native, &[], &inputs, true);
        parsed(&second);
        assert_eq!(first.stdout, second.stdout, "repeat/reversed file bytes");
        encoded(first)
    }
    fn compose(&self, left: &str, right: &str) -> String {
        encoded(self.run(
            &self.jq,
            &["-s", "-S", "-f", "compose-policy.jq"],
            &[("left.json", left), ("right.json", right)],
            false,
        ))
    }
    fn go(
        &self,
        providers: [Option<&str>; 4],
        context: Option<&str>,
        operation: &str,
        reverse: bool,
    ) -> Output {
        let mut inputs = vec![
            ("schema.cue", SCHEMA),
            ("bridge.cue", BRIDGE),
            ("selector.cue", SELECTOR),
        ];
        for (name, source) in ["helpers.cue", "flow.cue", "predicates.cue", "advance.cue"]
            .into_iter()
            .zip(providers)
        {
            if let Some(source) = source {
                inputs.push((name, source));
            }
        }
        if let Some(context) = context {
            inputs.push(("context.cue", context));
        }
        self.run(&self.cue, &[operation], &inputs, reverse)
    }
}
impl Drop for Probe {
    fn drop(&mut self) {
        fs::remove_dir_all(&self.dir).expect("retire scratch");
    }
}
fn providers() -> [Option<&'static str>; 4] {
    [Some(HELPERS), Some(FLOW), Some(PREDICATES), Some(ADVANCE)]
}

#[test]
fn complete_independent_trees_all_binary_orders_and_associations() {
    let probe = Probe::new();
    let expected = expected();
    let full = full_expected(&expected);
    assert_eq!(full["cases"].as_object().expect("all cases").len(), 15);
    for (module, names) in [
        (&expected[0], FLOW_NAMES.as_slice()),
        (&expected[1], PREDICATE_NAMES.as_slice()),
        (&expected[2], ["advance"].as_slice()),
    ] {
        let mut actual: Vec<_> = module["cases"]
            .as_object()
            .expect("module cases")
            .keys()
            .map(String::as_str)
            .collect();
        let mut names = names.to_vec();
        actual.sort();
        names.sort();
        assert_eq!(actual, names);
    }
    assert!(expected[1].get("formatVersion").is_none());
    assert!(expected[2].get("formatVersion").is_none());
    let mut previous = None;
    for reverse in [false, true] {
        let mut modules = Vec::new();
        for ((companion, source), want) in
            [(HELPERS, FLOW), (HELPERS, PREDICATES), (PACKAGE, ADVANCE)]
                .into_iter()
                .zip(&expected)
        {
            for (a, b) in [(companion, source), (source, companion)] {
                assert_eq!(
                    serde_json::from_str::<Value>(&export(a, b).expect("library export"))
                        .expect("library JSON"),
                    *want
                );
            }
            let output = probe.native(companion, source, reverse);
            assert_eq!(
                serde_json::from_str::<Value>(&output).expect("module JSON"),
                *want
            );
            modules.push(output);
        }
        for [a, b, c] in [
            [0, 1, 2],
            [0, 2, 1],
            [1, 0, 2],
            [1, 2, 0],
            [2, 0, 1],
            [2, 1, 0],
        ] {
            let left = probe.compose(&probe.compose(&modules[a], &modules[b]), &modules[c]);
            let right = probe.compose(&modules[a], &probe.compose(&modules[b], &modules[c]));
            assert_eq!(left, right);
            assert_eq!(
                serde_json::from_str::<Value>(&left).expect("composed JSON"),
                full
            );
            if let Some(bytes) = &previous {
                assert_eq!(&left, bytes);
            }
            previous = Some(left);
        }
        let go = probe.go(providers(), None, "export", reverse);
        assert_eq!(parsed(&go), full);
        let sorted = encoded(probe.run(
            &probe.jq,
            &["-S", "."],
            &[(
                "go.json",
                std::str::from_utf8(&go.stdout).expect("Go JSON UTF-8"),
            )],
            false,
        ));
        assert_eq!(Some(sorted), previous);
    }
}

#[test]
fn unknown_helpers_are_setup_errors_but_all_fifteen_slots_are_required() {
    let probe = Probe::new();
    for source in [FLOW, PREDICATES] {
        for (a, b) in [(PACKAGE, source), (source, PACKAGE)] {
            assert!(matches!(export(a, b), Err(Error::Unknown(_))));
        }
        failed(&probe.run(
            &probe.native,
            &[],
            &[("package.cue", PACKAGE), ("source.cue", source)],
            false,
        ));
    }
    let mut missing_helpers = providers();
    missing_helpers[0] = None;
    let unknown = probe.go(missing_helpers, None, "export", false);
    failed(&unknown);
    assert!(String::from_utf8_lossy(&unknown.stderr).contains("reference"));
    assert!(!String::from_utf8_lossy(&unknown.stderr).contains("incomplete value"));
    for index in 1..4 {
        let mut missing = providers();
        missing[index] = None;
        for reverse in [false, true] {
            let output = probe.go(missing, None, "export", reverse);
            failed(&output);
            assert!(String::from_utf8_lossy(&output.stderr).contains("incomplete value"));
            assert!(probe.go(missing, None, "eval", reverse).status.success());
        }
    }
    let full = full_expected(&expected());
    for name in full["cases"].as_object().expect("full cases").keys() {
        let mut missing = full.clone();
        missing["cases"]
            .as_object_mut()
            .expect("mutable cases")
            .remove(name);
        let data = serde_json::to_string(&missing).expect("missing-case JSON");
        let output = probe.run(
            &probe.cue,
            &["export"],
            &[
                ("schema.cue", SCHEMA),
                ("bridge.cue", BRIDGE),
                ("selector.cue", SELECTOR),
                ("data.json", &data),
            ],
            false,
        );
        failed(&output);
        assert!(
            String::from_utf8_lossy(&output.stderr).contains("incomplete value"),
            "required {name}"
        );
    }
    assert_eq!(
        parsed(&probe.go(providers(), None, "export", false)),
        full,
        "recovery"
    );
}

#[test]
fn raw_unicode_refines_live_alternative_not_materialized_default() {
    let probe = Probe::new();
    assert!(
        ADVANCE.contains("| string"),
        "raw alternative must survive refactoring"
    );
    let mut modules = expected();
    let default = full_expected(&modules);
    modules[2]["cases"]["advance"] = text(UNICODE_STEP);
    let unicode = full_expected(&modules);
    let variant = ADVANCE.replace("cursor.advance()?;", "cursor.advance_char()?;");
    assert_ne!(variant, ADVANCE);
    assert!(variant.contains("| string"));
    for reverse in [false, true] {
        assert_eq!(
            parsed(&probe.go(providers(), Some(UNICODE), "export", reverse)),
            unicode
        );
        assert_eq!(
            serde_json::from_str::<Value>(&probe.native(PACKAGE, &variant, reverse))
                .expect("variant JSON"),
            modules[2]
        );
        let mut changed = providers();
        changed[3] = Some(&variant);
        assert_eq!(parsed(&probe.go(changed, None, "export", reverse)), unicode);
        let materialized = serde_json::to_string(&default).expect("default JSON");
        for operation in ["export", "eval"] {
            let output = probe.run(
                &probe.cue,
                &[operation],
                &[
                    ("schema.cue", SCHEMA),
                    ("bridge.cue", BRIDGE),
                    ("selector.cue", SELECTOR),
                    ("data.json", &materialized),
                    ("context.cue", UNICODE),
                ],
                reverse,
            );
            failed(&output);
            assert!(String::from_utf8_lossy(&output.stderr).contains("conflicting values"));
        }
    }
}

#[test]
fn source_changes_are_not_filename_answers_and_mixed_documents_stay_excluded() {
    let probe = Probe::new();
    // Independent programs retain their own unchanged 4096-step ledgers.
    // Combining the ordinary owners is not admitted by silently raising fuel.
    let whole = format!(
        "{FLOW}\n{}",
        PREDICATES
            .strip_prefix("package bootstrap")
            .expect("predicate package")
    );
    assert_eq!(
        export(HELPERS, &whole),
        Err(Error::Limit("evaluation steps"))
    );
    let limited = probe.run(
        &probe.native,
        &[],
        &[("helpers.cue", HELPERS), ("whole.cue", &whole)],
        false,
    );
    failed(&limited);
    assert!(String::from_utf8_lossy(&limited.stderr).contains("evaluation steps"));
    let renamed_helpers = HELPERS.replace("#Scan", "#Renamed");
    for source in [FLOW, PREDICATES] {
        assert_eq!(
            export(HELPERS, source).expect("original helpers"),
            export(&renamed_helpers, &source.replace("#Scan", "#Renamed"))
                .expect("renamed helpers")
        );
    }
    let changed_helpers = HELPERS.replace("cursor.step()?;", "cursor.step()?; /* shared */");
    assert_ne!(changed_helpers, HELPERS);
    let mut want = expected()[0].clone();
    fn replace_step(value: &mut Value) {
        match value {
            Value::String(s) if s == "cursor.step()?;\n" => {
                *s = "cursor.step()?; /* shared */\n".into()
            }
            Value::Array(items) => items.iter_mut().for_each(replace_step),
            Value::Object(fields) => fields.values_mut().for_each(replace_step),
            _ => (),
        }
    }
    replace_step(&mut want);
    assert_eq!(
        serde_json::from_str::<Value>(&probe.native(&changed_helpers, FLOW, false))
            .expect("helper variant JSON"),
        want
    );
    let flow = FLOW.replace("cursor.set_flag(", "cursor.changed_flag(");
    let mut want = expected()[0].clone();
    want["cases"]["setFlag"]["parts"][1] = text("cursor.changed_flag(");
    assert_eq!(
        serde_json::from_str::<Value>(&probe.native(HELPERS, &flow, false))
            .expect("flow variant JSON"),
        want
    );
    let predicates = PREDICATES.replace("cursor.peek().is_some()", "cursor.peek().is_changed()");
    let mut want = expected()[1].clone();
    want["cases"]["hasByte"]["else"] = text("cursor.peek().is_changed()");
    assert_eq!(
        serde_json::from_str::<Value>(&probe.native(HELPERS, &predicates, false))
            .expect("predicate variant JSON"),
        want
    );
    for source in ["package bootstrap\n{}", FLOW, PREDICATES] {
        let ordinary = format!(
            "{HELPERS}\n{}",
            source
                .strip_prefix("package bootstrap")
                .expect("source package")
        );
        for (a, b) in [(ordinary.as_str(), ADVANCE), (ADVANCE, ordinary.as_str())] {
            assert!(matches!(export(a, b), Err(Error::Unsupported(_))));
        }
        failed(&probe.run(
            &probe.native,
            &[],
            &[("ordinary.cue", &ordinary), ("marked.cue", ADVANCE)],
            false,
        ));
    }
    // Materializable DATA is not necessarily a valid lowering instruction.
    let invalid = ADVANCE.replace("op: \"text\"", "op: \"unknownTestInstruction\"");
    let mut want = expected()[2].clone();
    want["cases"]["advance"]["op"] = json!("unknownTestInstruction");
    assert_eq!(
        serde_json::from_str::<Value>(&probe.native(PACKAGE, &invalid, false))
            .expect("invalid DATA JSON"),
        want
    );
    let mut inputs = providers();
    inputs[3] = Some(&invalid);
    failed(&probe.go(inputs, None, "export", false));
    failed(&probe.run(&probe.native, &[], &[("package.cue", PACKAGE)], false));
    assert!(
        Command::new(probe.dir.join("missing-tool"))
            .env_clear()
            .output()
            .is_err(),
        "spawn failure is setup, not Incomplete"
    );
    let malformed =
        "package bootstrap\n{cases: {advance: {op: \"text\", value: *\"x\" | string}}}\ngarbage";
    assert!(export(PACKAGE, malformed).is_err());
    failed(&probe.run(
        &probe.native,
        &[],
        &[("package.cue", PACKAGE), ("broken.cue", malformed)],
        false,
    ));
    assert_eq!(
        serde_json::from_str::<Value>(&probe.native(PACKAGE, ADVANCE, false))
            .expect("recovered JSON"),
        expected()[2]
    );
}
