// Independently authored DSL trees, never native/Go exports, source parsing or
// feasibility captures. Expected assembly below is not the production composer.
fn text(value: &str) -> Value {
    json!({"op":"text","value":value})
}
fn field(op: &str, name: &str) -> Value {
    json!({"op":op,"field":name})
}
fn concat(parts: Vec<Value>) -> Value {
    json!({"op":"concat","parts":parts})
}
fn select(name: &str, cases: Value) -> Value {
    json!({"op":"select","field":name,"cases":cases})
}
fn lower(name: &str) -> Value {
    field("lower", name)
}
fn expected_body() -> Value {
    let mut headers = json!({});
    for (target, imports, frame) in [
        (
            "parser",
            "use crate::parser::{Error, Frame};",
            "Frame<'_, '_>",
        ),
        (
            "list",
            "use crate::{Error, runtime::ListFrame};",
            "ListFrame<'_>",
        ),
        (
            "record",
            "use crate::{Error, runtime::RecordFrame};",
            "RecordFrame<'_>",
        ),
        (
            "conjunction",
            "use crate::{Error, runtime::ConjunctionFrame};",
            "ConjunctionFrame<'_>",
        ),
        (
            "slice",
            "use crate::{Error, runtime::SliceFrame};",
            "SliceFrame<'_>",
        ),
    ] {
        headers[target] = text(&format!(
            "// Generated by bootstrap-pratt-codegen. Do not edit by hand.\n{imports}\npub fn execute(_frame: &mut {frame}) -> Result<(), Error> {{\n"
        ));
    }
    let conditional = concat(vec![
        text("_frame.step()?;\nif "),
        lower("condition"),
        text(" {\n"),
        field("list", "then"),
        json!({"op":"ifEmpty","field":"else","then":text(""),
            "else":concat(vec![text("} else {\n"),field("list","else")])}),
        text("}\n"),
    ]);
    json!({"formatVersion":1,"cases":{
        "action":concat(vec![text("_frame.step()?;\n_frame."),
            json!({"op":"identifier","field":"action","snake":true}),text("()?;\n")]),
        "program":concat(vec![select("target",headers),field("list","body"),
            select("tail",json!({"return":text("}\n"),"value":text("Ok(())\n}\n")}))]),
        "return":select("position",json!({"early":text("_frame.step()?;\nreturn Ok(());\n"),
            "tail":text("_frame.step()?;\nOk(())\n")})),
        "minimum":text("_frame.minimum()"),
        "tokenLength":text("_frame.token_length()?"),
        "precedence":text("_frame.precedence()?"),
        "integer":concat(vec![field("unsigned","value"),text("u8")]),
        "hasOperator":text("_frame.has_operator()"),
        "leftAssociative":text("_frame.left_associative()?"),
        "groupOpen":text("_frame.group_open()?"),
        "hasBound":text("_frame.has_bound()?"),
        "hasIdentifier":text("_frame.has_identifier()?"),
        "hasCall":text("_frame.has_call()?"),
        "hasRecord":text("_frame.has_record()?"),
        "hasConjunction":text("_frame.has_conjunction()?"),
        "hasRecordField":text("_frame.has_record_field()?"),
        "hasList":text("_frame.has_list()?"),
        "hasSlice":text("_frame.has_slice()?"),
        "hasIndex":text("_frame.has_index()?"),
        "hasPostfix":text("_frame.has_postfix()?"),
        "hasSelectorString":text("_frame.has_selector_string()?"),
        "hasListElement":text("_frame.has_list_element()?"),
        "hasString":text("_frame.has_string()?"),
        "hasNegation":text("_frame.has_negation()?"),
        "hasNot":text("_frame.has_not()?"),
        "hasLower":text("_frame.has_lower()?"),
        "hasUpper":text("_frame.has_upper()?"),
        "sliceKindIs":concat(vec![text("_frame.slice_kind_is(crate::unification::Kind::"),
            json!({"op":"identifier","field":"kind","upperFirst":true}),text(")?")]),
        "defaultSliceLower":concat(vec![text("_frame.step()?;\n_frame.default_slice_lower("),
            field("signed","value"),text(")?;\n")]),
        "hasItem":text("_frame.has_item()?"),
        "itemKindIs":concat(vec![text("_frame.item_kind_is(crate::unification::Kind::"),
            json!({"op":"identifier","field":"kind","upperFirst":true}),text(")?")]),
        "boolean":field("boolean","value"),
        "atLeast":concat(vec![lower("left"),text(" >= "),lower("right")]),
        "and":concat(vec![lower("left"),text(" && "),lower("right")]),
        "setBindingPower":concat(vec![text("_frame.step()?;\n_frame.set_binding_power("),
            lower("value"),text(")?;\n")]),
        "while":concat(vec![text("while { _frame.step()?; "),lower("condition"),text(" } {\n"),
            field("list","body"),text("}\n")]),
        "if":conditional
    }})
}
fn expected_add() -> Value {
    json!({"cases":{"add":concat(vec![text("_frame.binding_add("),lower("left"),
        text(", "),lower("right"),text(")?")])}})
}
fn expected_tables() -> Value {
    let mut aliases = json!({});
    let mut calls = json!({});
    let mut actions = json!({});
    for (key, value) in MINIMUM {
        aliases[key] = json!("parseMinimum");
        calls[key] = text(value);
    }
    for (key, value) in SELECTORS {
        actions[key] = text(value);
    }
    json!({"aliases":aliases,"cases":{
        "selectorAction":concat(vec![text("_frame.step()?;\n_frame."),select("action",actions),text("()?;\n")]),
        "parseMinimum":concat(vec![text("_frame.step()?;\n_frame."),select("op",calls),
            text("("),lower("minimum"),text(")?;\n")])
    }})
}
fn full_expected() -> Value {
    let mut full = expected_body();
    let tables = expected_tables();
    full["aliases"] = tables["aliases"].clone();
    for (name, instruction) in tables["cases"].as_object().expect("table cases") {
        assert!(
            full["cases"]
                .as_object_mut()
                .expect("body cases")
                .insert(name.clone(), instruction.clone())
                .is_none()
        );
    }
    full["cases"]["add"] = expected_add()["cases"]["add"].clone();
    full
}
fn decode(data: &str) -> Value {
    serde_json::from_str(data).expect("complete JSON")
}
fn parsed(out: &Output) -> Value {
    assert!(
        out.status.success(),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
    assert!(out.stdout.len() <= 65536);
    serde_json::from_slice(&out.stdout).expect("bounded complete JSON")
}
fn failed(out: &Output, message: &str) {
    assert!(!out.status.success());
    assert!(out.stdout.is_empty(), "no partial JSON");
    assert!(
        String::from_utf8_lossy(&out.stderr).contains(message),
        "{}",
        String::from_utf8_lossy(&out.stderr)
    );
}
fn executable(tool: &Path) {
    assert!(tool.is_absolute());
    fs::File::open(tool).expect("readable mandatory tool");
    assert_ne!(
        fs::metadata(tool)
            .expect("tool metadata")
            .permissions()
            .mode()
            & 0o111,
        0
    );
}
struct Probe {
    dir: PathBuf,
    native: PathBuf,
    cue: PathBuf,
    jq: PathBuf,
}
impl Probe {
    fn new() -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let dir = std::env::temp_dir().join(format!(
            "pratt-policy-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir(&dir).expect("fresh owned scratch");
        fs::create_dir(dir.join("home")).expect("owned HOME");
        let provider = |name| {
            std::env::split_paths(&std::env::var_os("PATH").expect("pinned PATH"))
                .map(|p| p.join(name))
                .find(|p| p.is_file())
                .expect("mandatory pinned tool")
                .canonicalize()
                .expect("absolute tool")
        };
        let probe = Self {
            dir,
            native: PathBuf::from(env!("CARGO_BIN_EXE_cuestacean-spec-export")),
            cue: provider("cue"),
            jq: provider("jq"),
        };
        for tool in [&probe.native, &probe.cue, &probe.jq] {
            executable(tool);
        }
        probe
    }
    fn run(&self, tool: &Path, args: &[&str], inputs: &[(&str, &str)], reverse: bool) -> Output {
        executable(tool);
        let mut paths = Vec::new();
        for (name, source) in inputs {
            let path = self.dir.join(name);
            fs::write(&path, source).expect("explicit source");
            paths.push(path);
        }
        if reverse {
            paths.reverse();
        }
        Command::new(tool)
            .args(args)
            .args(paths)
            .env_clear()
            .env("HOME", self.dir.join("home"))
            .env("PATH", "/unusable")
            .current_dir(&self.dir)
            .output()
            .expect("mandatory process setup")
    }
    fn native(&self, source: &str, reverse: bool) -> Output {
        self.run(
            &self.native,
            &[],
            &[("package.cue", PACKAGE), ("owner.cue", source)],
            reverse,
        )
    }
    fn go(&self, mode: &str, providers: &[(&str, &str)], context: bool, reverse: bool) -> Output {
        let mut inputs = vec![
            ("schema.cue", SCHEMA),
            ("bridge.cue", BRIDGE),
            ("selector.cue", SELECTOR),
        ];
        inputs.extend_from_slice(providers);
        if context {
            inputs.push(("context.cue", CONTEXT));
        }
        self.run(&self.cue, &[mode], &inputs, reverse)
    }
    fn raw(&self, context: bool, reverse: bool) -> Output {
        self.go(
            "export",
            &[("body.cue", BODY), ("add.cue", ADD), ("tables.cue", TABLES)],
            context,
            reverse,
        )
    }
    fn compose(&self, left: &Value, right: &Value) -> Output {
        fs::write(self.dir.join("compose.jq"), COMPOSE).expect("unchanged composer");
        self.run(
            &self.jq,
            &["-s", "-S", "-f", "compose.jq"],
            &[
                ("left.json", &left.to_string()),
                ("right.json", &right.to_string()),
            ],
            false,
        )
    }
}
impl Drop for Probe {
    fn drop(&mut self) {
        fs::remove_dir_all(&self.dir).expect("retire scratch");
    }
}

#[test]
fn complete_independent_trees_native_cli_oracle_and_closed_helpers() {
    let probe = Probe::new();
    let body = expected_body();
    let keys: Vec<_> = body["cases"]
        .as_object()
        .expect("cases")
        .keys()
        .map(String::as_str)
        .collect();
    let mut names: Vec<_> = ROOTS.split_whitespace().collect();
    names.sort_unstable();
    assert_eq!(keys, names);
    assert_eq!(keys.len(), 37);
    let full = full_expected();
    assert_eq!(full["cases"].as_object().expect("cases").len(), 40);
    assert_eq!(full["aliases"].as_object().expect("aliases").len(), 7);
    assert_eq!(full["formatVersion"], 1);
    assert!(BODY.contains("#PrattLoweringBody"));
    assert!(BODY.contains("let L") && BODY.contains("let R"));
    assert!(!ADD.contains("let ") && !ADD.contains("#PrattLoweringBody"));
    for (source, want) in [
        (BODY, body),
        (ADD, expected_add()),
        (TABLES, expected_tables()),
    ] {
        for reverse in [false, true] {
            let (a, b) = if reverse {
                (source, PACKAGE)
            } else {
                (PACKAGE, source)
            };
            assert_eq!(
                decode(&export(a, b).expect("existing profile succeeds")),
                want
            );
            for _ in 0..2 {
                assert_eq!(parsed(&probe.native(source, reverse)), want);
            }
            assert_eq!(
                parsed(&probe.run(
                    &probe.cue,
                    &["export"],
                    &[
                        ("different-package.cue", PACKAGE),
                        ("different-owner.cue", source)
                    ],
                    reverse
                )),
                want
            );
        }
    }
    let renamed = BODY
        .replace("#PrattLoweringBody", "#OtherBody")
        .replace("let L", "let LeftLeaf")
        .replace("let R", "let RightLeaf")
        .replace("[L,", "[LeftLeaf,")
        .replace(", R]", ", RightLeaf]");
    assert_ne!(renamed, BODY);
    for reverse in [false, true] {
        assert_eq!(parsed(&probe.native(&renamed, reverse)), expected_body());
        assert_eq!(
            parsed(&probe.go(
                "export",
                &[
                    ("renamed-body.cue", &renamed),
                    ("add.cue", ADD),
                    ("tables.cue", TABLES)
                ],
                false,
                reverse
            )),
            full
        );
        assert_eq!(parsed(&probe.raw(false, reverse)), full);
        let mut forced = full.clone();
        forced["cases"]["add"] = lower("left");
        assert_eq!(parsed(&probe.raw(true, reverse)), forced);
        assert_eq!(
            parsed(&probe.go(
                "export",
                &[("full.json", &full.to_string())],
                false,
                reverse
            )),
            full
        );
    }
}

#[test]
fn every_order_both_associations_and_structural_collisions() {
    let probe = Probe::new();
    let modules = [BODY, ADD, TABLES].map(|s| parsed(&probe.native(s, false)));
    for [a, b, c] in [
        [0, 1, 2],
        [0, 2, 1],
        [1, 0, 2],
        [1, 2, 0],
        [2, 0, 1],
        [2, 1, 0],
    ] {
        for _ in 0..2 {
            let ab = parsed(&probe.compose(&modules[a], &modules[b]));
            let bc = parsed(&probe.compose(&modules[b], &modules[c]));
            assert_eq!(parsed(&probe.compose(&ab, &modules[c])), full_expected());
            assert_eq!(parsed(&probe.compose(&modules[a], &bc)), full_expected());
        }
    }
    for value in [
        json!({"nested":{"leaf":1}}),
        json!({"nested":{"leaf":[1]}}),
        json!({"nested":{"leaf":[]}}),
    ] {
        failed(&probe.compose(&value, &value), "overlapping module leaf");
    }
    failed(
        &probe.compose(&json!([]), &json!({})),
        "module roots must be objects",
    );
    assert_eq!(
        parsed(&probe.compose(&json!({"a":[1,2]}), &json!({"b":[3]}))),
        json!({"a":[1,2],"b":[3]})
    );
}

#[test]
fn all_47_required_slots_are_incomplete_without_raw_provider_filling() {
    let probe = Probe::new();
    let modules = [BODY, ADD, TABLES].map(|s| parsed(&probe.native(s, false)));
    let full = parsed(&probe.compose(
        &parsed(&probe.compose(&modules[0], &modules[1])),
        &modules[2],
    ));
    assert_eq!(full, full_expected());
    let slots: Vec<_> = ["cases", "aliases"]
        .into_iter()
        .flat_map(|section| {
            full[section]
                .as_object()
                .expect("required section")
                .keys()
                .map(move |name| (section, name.clone()))
        })
        .collect();
    assert_eq!(slots.len(), 47);
    for (section, name) in slots {
        let mut missing = full.clone();
        assert!(
            missing[section]
                .as_object_mut()
                .expect("section")
                .remove(&name)
                .is_some()
        );
        let data = missing.to_string();
        for reverse in [false, true] {
            // No body/add/table raw owner: otherwise it could refill the hole.
            let providers = [("missing.json", data.as_str())];
            let eval = probe.go("eval", &providers, false, reverse);
            assert!(
                eval.status.success(),
                "{}",
                String::from_utf8_lossy(&eval.stderr)
            );
            failed(
                &probe.go("export", &providers, false, reverse),
                "incomplete value",
            );
        }
    }
    for omitted in 0..3 {
        let owners = [("body.cue", BODY), ("add.cue", ADD), ("tables.cue", TABLES)];
        let providers: Vec<_> = owners
            .into_iter()
            .enumerate()
            .filter_map(|(i, owner)| (i != omitted).then_some(owner))
            .collect();
        failed(
            &probe.go("export", &providers, false, false),
            "incomplete value",
        );
    }
    let unknown = BODY.replace("#PrattLoweringBody:", "#DifferentBody:");
    assert!(matches!(export(PACKAGE, &unknown), Err(Error::Unknown(_))));
    let out = probe.native(&unknown, false);
    failed(&out, "unknown reference: #PrattLoweringBody");
    assert_eq!(parsed(&probe.native(BODY, false)), expected_body());
}

#[test]
fn raw_preferences_literal_variants_priority_and_late_conflict() {
    let probe = Probe::new();
    let forced_context = "\n{cases: {add: {op: \"lower\"}}}\n";
    let mut forced = expected_add();
    forced["cases"]["add"] = lower("left");
    let preferred_variant = ADD.replace("_frame.binding_add(", "_frame.changed_add(");
    assert_ne!(preferred_variant, ADD);
    let mut changed_preferred = expected_add();
    changed_preferred["cases"]["add"]["parts"][0] = text("_frame.changed_add(");
    // Only Q's field literal changes; P's two left/right helper values stay intact.
    let alternate_variant = ADD.replacen(
        "| {op: \"lower\", field: \"left\"}",
        "| {op: \"lower\", field: \"right\"}",
        1,
    );
    assert_ne!(alternate_variant, ADD);
    let mut changed_alternate = forced.clone();
    changed_alternate["cases"]["add"] = lower("right");
    let priority = ADD
        .replacen("*{op: \"concat\"", "{op: \"concat\"", 1)
        .replacen("| {op: \"lower\"", "| *{op: \"lower\"", 1);
    assert_ne!(priority, ADD);
    let generic = ADD
        .replace("op:", "tag:")
        .replace("\"concat\"", "\"preferred\"")
        .replace("\"lower\"", "\"alternate\"");
    let generic_want = json!({"cases":{"add":{"tag":"preferred","parts":[
        {"tag":"text","value":"_frame.binding_add("},{"tag":"alternate","field":"left"},
        {"tag":"text","value":", "},{"tag":"alternate","field":"right"},{"tag":"text","value":")?"}]}}});
    for reverse in [false, true] {
        for (source, want) in [
            (ADD.to_owned(), expected_add()),
            (format!("{ADD}{forced_context}"), forced.clone()),
            (preferred_variant.clone(), changed_preferred.clone()),
            (alternate_variant.clone(), expected_add()),
            (
                format!("{alternate_variant}{forced_context}"),
                changed_alternate.clone(),
            ),
            (priority.clone(), forced.clone()),
            (generic.clone(), generic_want.clone()),
        ] {
            assert_eq!(parsed(&probe.native(&source, reverse)), want);
            assert_eq!(
                parsed(&probe.run(
                    &probe.cue,
                    &["export"],
                    &[("package.cue", PACKAGE), ("variant.cue", &source)],
                    reverse
                )),
                want
            );
        }
        let full = full_expected().to_string();
        failed(
            &probe.go("export", &[("selected.json", &full)], true, reverse),
            "conflicting values",
        );
    }
    // Reordering alternatives while retaining P's mark must not change priority.
    let start = ADD.find('*').expect("marked preferred branch");
    let split = ADD.find(" | ").expect("flat original alternatives");
    let q_end = ADD.rfind('}').expect("root close");
    let q_end = ADD[..q_end].rfind('}').expect("cases close");
    let swapped = format!(
        "{}{} | {}}}}}",
        &ADD[..start],
        ADD[split + 3..q_end].trim(),
        ADD[start..split].trim()
    );
    for reverse in [false, true] {
        assert_eq!(parsed(&probe.native(&swapped, reverse)), expected_add());
        assert_eq!(
            parsed(&probe.run(
                &probe.cue,
                &["export"],
                &[("package.cue", PACKAGE), ("swapped.cue", &swapped)],
                reverse
            )),
            expected_add()
        );
    }
}

#[test]
fn profiles_work_guard_setup_errors_and_recovery_do_not_fallback() {
    let probe = Probe::new();
    assert!(matches!(
        export_with_limit(PACKAGE, BODY, 1),
        Err(Error::Limit("evaluation steps"))
    ));
    assert_eq!(
        decode(&export(PACKAGE, BODY).expect("body within unchanged 4096")),
        expected_body()
    );
    let combined = format!(
        "{BODY}\n{}\n{}",
        ADD.replacen("package bootstrap", "", 1),
        TABLES.replacen("package bootstrap", "", 1)
    );
    assert!(matches!(
        export(PACKAGE, &combined),
        Err(Error::Unsupported(_))
    ));
    let out = probe.native(&combined, false);
    assert!(!out.status.success() && out.stdout.is_empty());
    let malformed = ADD.replace("*{", "**{");
    assert_eq!(
        export(PACKAGE, &malformed),
        Err(Error::Unsupported("one tagged choice required"))
    );
    failed(
        &probe.native(&malformed, false),
        "unsupported: one tagged choice required",
    );
    assert_eq!(parsed(&probe.raw(false, false)), full_expected());
    assert_eq!(parsed(&probe.native(ADD, false)), expected_add());
    // Actual compiler complete-source effects for all three owners, schema/typed
    // no-Rust checks and compiled adversaries are Nix-owned, never test providers.
}
