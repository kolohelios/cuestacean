fn expected_policy() -> Value {
    let mut policy = expected_body();
    policy["cases"]["integer"] = json!({"op":"concat","parts":[
        {"op":"text","value":"Value::from("},
        {"op":"signed","field":"value"},
        {"op":"text","value":"i64)"}
    ]});
    policy
}
fn parsed(output: &Output) -> Value {
    assert!(
        output.status.success(),
        "{}",
        String::from_utf8_lossy(&output.stderr)
    );
    serde_json::from_slice(&output.stdout).expect("complete exact-integer JSON")
}
fn failed(output: &Output) {
    assert!(!output.status.success(), "unexpected success");
    assert!(output.stdout.is_empty(), "no partial JSON");
    assert!(!output.stderr.is_empty(), "mandatory diagnostic");
}
fn executable(path: &Path) {
    assert!(path.is_absolute(), "absolute provider");
    fs::File::open(path).expect("readable provider");
    assert_ne!(
        fs::metadata(path)
            .expect("mandatory provider metadata")
            .permissions()
            .mode()
            & 0o111,
        0
    );
}
struct Probe {
    directory: PathBuf,
    native: PathBuf,
    cue: PathBuf,
    jq: PathBuf,
}
impl Probe {
    fn new() -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let directory = std::env::temp_dir().join(format!(
            "cuestacean-ast-policy-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        assert!(directory.is_absolute(), "absolute owned scratch directory");
        fs::create_dir(&directory).expect("fresh owned scratch");
        fs::create_dir(directory.join("home")).expect("fresh owned HOME");
        let provider = |name| {
            std::env::split_paths(&std::env::var_os("PATH").expect("pinned toolchain PATH"))
                .map(|path| path.join(name))
                .find(|path| path.is_file())
                .expect("mandatory pinned provider")
                .canonicalize()
                .expect("canonical absolute pinned provider")
        };
        let probe = Self {
            directory,
            native: PathBuf::from(env!("CARGO_BIN_EXE_cuestacean-spec-export")),
            cue: provider("cue"),
            jq: provider("jq"),
        };
        for binary in [&probe.native, &probe.cue, &probe.jq] {
            executable(binary);
        }
        fs::write(probe.directory.join("compose-policy.jq"), COMPOSE)
            .expect("production composition script in owned scratch");
        probe
    }
    fn run(&self, binary: &Path, args: &[&str], inputs: &[(&str, &str)], reverse: bool) -> Output {
        let mut names = Vec::new();
        for (name, source) in inputs {
            fs::write(self.directory.join(name), source).expect("fresh probe input file");
            names.push(*name);
        }
        if reverse {
            names.reverse();
        }
        Command::new(binary)
            .env_clear()
            .env("PATH", "/unusable")
            .env("HOME", self.directory.join("home"))
            .current_dir(&self.directory)
            .args(args)
            .args(names)
            .output()
            .expect("fresh mandatory process")
    }
    fn native(&self, source: &str, reverse: bool) -> Output {
        self.run(
            &self.native,
            &[],
            &[("z-package.cue", PACKAGE), ("a-source.cue", source)],
            reverse,
        )
    }
    fn compose(&self, modules: &[&str], reverse: bool) -> Output {
        let names: Vec<_> = (0..modules.len())
            .map(|i| format!("module-{i}.json"))
            .collect();
        let inputs: Vec<_> = names
            .iter()
            .zip(modules)
            .map(|(name, source)| (name.as_str(), *source))
            .collect();
        self.run(
            &self.jq,
            &["-s", "-S", "-f", "compose-policy.jq"],
            &inputs,
            reverse,
        )
    }
    fn go(
        &self,
        body: Option<&str>,
        integer: Option<&str>,
        context: Option<&str>,
        eval: bool,
        reverse: bool,
    ) -> Output {
        let mut inputs = vec![
            ("schema.cue", SCHEMA),
            ("bridge.cue", BRIDGE),
            ("selector.cue", SELECTOR),
        ];
        if let Some(body) = body {
            inputs.push(("body.cue", body));
        }
        if let Some(integer) = integer {
            inputs.push(("integer.cue", integer));
        }
        if let Some(context) = context {
            inputs.push(("context.cue", context));
        }
        self.run(
            &self.cue,
            &[if eval { "eval" } else { "export" }],
            &inputs,
            reverse,
        )
    }
}
impl Drop for Probe {
    fn drop(&mut self) {
        fs::remove_dir_all(&self.directory).expect("retire owned scratch directory");
    }
}

#[test]
fn complete_body_and_policy_agree_with_independent_trees_and_raw_go() {
    let probe = Probe::new();
    let expected = expected_policy();
    let mut previous = None;
    for reverse in [false, true] {
        let (a, b) = if reverse {
            (BODY, PACKAGE)
        } else {
            (PACKAGE, BODY)
        };
        assert_eq!(
            serde_json::from_str::<Value>(&export(a, b).expect("native library body export"))
                .expect("complete native library body JSON"),
            expected_body()
        );
        for _ in 0..2 {
            let body = probe.native(BODY, reverse);
            assert_eq!(parsed(&body), expected_body());
            let integer = probe.native(INTEGER, reverse);
            assert_eq!(
                parsed(&integer),
                json!({"cases":{"integer":expected["cases"]["integer"]}})
            );
            let body = String::from_utf8(body.stdout).expect("native body JSON UTF-8");
            let integer = String::from_utf8(integer.stdout).expect("native integer JSON UTF-8");
            let composed = probe.compose(&[&body, &integer], reverse);
            assert_eq!(parsed(&composed), expected);
            if let Some(bytes) = &previous {
                assert_eq!(&composed.stdout, bytes);
            }
            previous = Some(composed.stdout.clone());
            let go = probe.go(Some(BODY), Some(INTEGER), None, false, reverse);
            assert_eq!(parsed(&go), expected);
            // Canonicalize only through sorting/identity, never numeric arithmetic.
            let go = String::from_utf8(go.stdout).expect("raw Go policy JSON UTF-8");
            let sorted = probe.run(&probe.jq, &["-S", "."], &[("oracle.json", &go)], false);
            parsed(&sorted);
            assert_eq!(composed.stdout, sorted.stdout);
        }
    }
}

#[test]
fn all_seven_go_slots_require_both_providers_before_export() {
    let probe = Probe::new();
    for (body, integer) in [(None, Some(INTEGER)), (Some(BODY), None), (None, None)] {
        for reverse in [false, true] {
            let output = probe.go(body, integer, None, false, reverse);
            failed(&output);
            assert!(String::from_utf8_lossy(&output.stderr).contains("incomplete value"));
            let evaluation = probe.go(body, integer, None, true, reverse);
            assert!(
                evaluation.status.success(),
                "{}",
                String::from_utf8_lossy(&evaluation.stderr)
            );
        }
    }
}

#[test]
fn raw_context_is_live_but_materialized_default_is_not_a_late_override() {
    let probe = Probe::new();
    let body = probe.native(BODY, false);
    assert_eq!(parsed(&body), expected_body());
    let integer = probe.native(INTEGER, false);
    assert_eq!(
        parsed(&integer),
        json!({"cases":{"integer":expected_policy()["cases"]["integer"]}})
    );
    let body = String::from_utf8(body.stdout).expect("native body JSON UTF-8");
    let integer = String::from_utf8(integer.stdout).expect("native integer JSON UTF-8");
    let default = probe.compose(&[&body, &integer], false);
    assert_eq!(parsed(&default), expected_policy());
    let default = String::from_utf8(default.stdout).expect("composed default JSON UTF-8");
    for reverse in [false, true] {
        let context = "package bootstrap\n{cases: {integer: {op: \"text\", value: \"x\"}}}\n";
        let mut expected = expected_policy();
        expected["cases"]["integer"] = json!({"op":"text","value":"x"});
        assert_eq!(
            parsed(&probe.go(Some(BODY), Some(INTEGER), Some(context), false, reverse)),
            expected
        );
        for operation in ["export", "eval"] {
            failed(&probe.run(
                &probe.cue,
                &[operation],
                &[
                    ("schema.cue", SCHEMA),
                    ("bridge.cue", BRIDGE),
                    ("selector.cue", SELECTOR),
                    ("default.json", &default),
                    ("override.cue", context),
                ],
                reverse,
            ));
        }
    }
}

#[test]
fn production_composer_rejects_collisions_and_wrong_module_shapes() {
    let probe = Probe::new();
    for (a, b) in [
        (r#"{"cases":{"x":1}}"#, r#"{"cases":{"x":1}}"#),
        (r#"{"x":1}"#, r#"{"x":2}"#),
        (r#"{"x":[1]}"#, r#"{"x":[1]}"#),
        (r#"{"x":[]}"#, r#"{"x":[2]}"#),
        (r#"{"x":{}}"#, r#"{"x":1}"#),
        (r#"{"x":[]}"#, r#"{"x":{}}"#),
        (r#"{"x":null}"#, r#"{"x":null}"#),
        ("[]", "{}"),
        ("1", "{}"),
        ("null", "{}"),
        ("true", "{}"),
    ] {
        for reverse in [false, true] {
            failed(&probe.compose(&[a, b], reverse));
        }
    }
    // With zero file arguments jq reads stdin; Command::output supplies EOF.
    for modules in [vec![], vec!["{}"], vec!["{}", "{}", "{}"]] {
        failed(&probe.compose(&modules, false));
    }
}

#[test]
fn structural_composition_preserves_atomic_arrays_and_exact_integer_identity() {
    let probe = Probe::new();
    let a = r#"{"cases":{"a":[-9223372036854775808,9223372036854775807,9007199254740993]}}"#;
    let b = r#"{"formatVersion":1,"cases":{"b":{"literal":-9007199254740993}}}"#;
    let expected = json!({"formatVersion":1,"cases":{
        "a":[i64::MIN,i64::MAX,9_007_199_254_740_993i64],
        "b":{"literal":-9_007_199_254_740_993i64}
    }});
    let first = probe.compose(&[a, b], false);
    assert_eq!(parsed(&first), expected);
    let reversed = probe.compose(&[a, b], true);
    assert_eq!(parsed(&reversed), expected);
    assert_eq!(first.stdout, reversed.stdout);
}

#[test]
fn separate_native_modules_do_not_admit_a_mixed_marked_let_document() {
    for (a, b) in [(BODY, INTEGER), (INTEGER, BODY)] {
        assert!(matches!(export(a, b), Err(Error::Unsupported(_))));
    }
    let probe = Probe::new();
    for reverse in [false, true] {
        failed(&probe.run(
            &probe.native,
            &[],
            &[("body.cue", BODY), ("integer.cue", INTEGER)],
            reverse,
        ));
    }
}
