// Independent expected-data assembly only. Production construction NEVER calls it.
fn union(left: &mut Value, right: &Value) {
    let out = left.as_object_mut().expect("independent object namespace");
    for (key, value) in right.as_object().expect("independent object module") {
        if let Some(old) = out.get_mut(key) {
            union(old, value);
        } else {
            out.insert(key.clone(), value.clone());
        }
    }
}
fn expected_policy() -> Value {
    let mut out = json!({});
    for part in expected_parts() {
        union(&mut out, &part);
    }
    out
}
fn parsed(source: &str) -> Value {
    serde_json::from_str(source).expect("complete JSON")
}
fn decoded(output: Output) -> Value {
    assert_eq!(output.status.code(), Some(0), "{output:?}");
    assert!(
        output.stderr.is_empty(),
        "successful export diagnostics: {output:?}"
    );
    serde_json::from_slice(&output.stdout).expect("complete output JSON")
}
fn change(source: &str, from: &str, to: &str) -> String {
    assert_eq!(
        source.matches(from).count(),
        1,
        "unique source token {from}"
    );
    source.replacen(from, to, 1)
}
fn executable(path: &Path) {
    assert!(path.is_absolute());
    let metadata = fs::metadata(path).expect("mandatory tool metadata");
    assert!(metadata.is_file());
    fs::File::open(path).expect("readable mandatory tool");
    assert_ne!(metadata.permissions().mode() & 0o111, 0);
}
struct Probe {
    dir: PathBuf,
    native: PathBuf,
    cue: PathBuf,
    jq: PathBuf,
    shell: PathBuf,
    next: Cell<usize>,
}
impl Probe {
    fn new() -> Self {
        static NEXT: AtomicUsize = AtomicUsize::new(0);
        let dir = std::env::temp_dir().join(format!(
            "cuestacean280-EVIDENCE-policy-{}-{}",
            std::process::id(),
            NEXT.fetch_add(1, Ordering::Relaxed)
        ));
        fs::create_dir(&dir).expect("exclusive owned receipt directory");
        fs::create_dir(dir.join("home")).expect("owned HOME");
        let tool = |name| {
            let path = std::env::split_paths(&std::env::var_os("PATH").expect("pinned PATH"))
                .map(|p| p.join(name))
                .find(|p| p.is_file())
                .expect("mandatory pinned tool")
                .canonicalize()
                .expect("absolute tool");
            executable(&path);
            path
        };
        let native = PathBuf::from(env!("CARGO_BIN_EXE_cuestacean-spec-export"));
        executable(&native);
        Self {
            dir,
            native,
            cue: tool("cue"),
            jq: tool("jq"),
            shell: tool("sh"),
            next: Cell::new(0),
        }
    }
    // Every attempt, including setup/error attempts, owns separate retained receipts.
    fn run(&self, tool: &Path, args: &[&str], inputs: &[(&str, &str)], reverse: bool) -> Output {
        executable(tool);
        let id = self.next.get();
        self.next.set(id + 1);
        let dir = self.dir.join(format!("attempt-{id}"));
        fs::create_dir(&dir).expect("exclusive attempt");
        let mut paths = Vec::new();
        for (name, source) in inputs {
            let path = dir.join(name);
            fs::write(&path, source).expect("owned explicit input");
            paths.push(path);
        }
        if reverse {
            paths.reverse();
        }
        let out = Command::new(tool)
            .args(args)
            .args(&paths)
            .env_clear()
            .env("HOME", self.dir.join("home"))
            .env("PATH", "/nonexistent")
            .current_dir(&dir)
            .output()
            .expect("mandatory process setup, not semantic failure");
        fs::write(dir.join("stdout"), &out.stdout).expect("stdout receipt");
        fs::write(dir.join("stderr"), &out.stderr).expect("stderr receipt");
        fs::write(dir.join("status"), format!("{:?}\n", out.status.code()))
            .expect("status receipt");
        out
    }
    fn pair(&self, owner: &str, adapter: &str, reverse: bool) -> Output {
        self.run(
            &self.native,
            &[],
            &[("ordinary.cue", owner), ("unrelated.cue", adapter)],
            reverse,
        )
    }
    fn go_pair(&self, owner: &str, adapter: &str, reverse: bool) -> Output {
        self.run(
            &self.cue,
            &["export"],
            &[("ordinary.cue", owner), ("unrelated.cue", adapter)],
            reverse,
        )
    }
    fn compose(&self, left: &Value, right: &Value) -> Value {
        let a = left.to_string();
        let b = right.to_string();
        assert!(a.len() <= 65536 && b.len() <= 65536);
        let composer = self.dir.join("compose-policy.jq");
        if !composer.exists() {
            fs::write(&composer, COMPOSER).expect("unchanged composer");
        }
        let out = self.run(
            &self.jq,
            &["-s", "-S", "-f", composer.to_str().expect("path UTF-8")],
            &[("left.json", &a), ("right.json", &b)],
            false,
        );
        assert!(out.stdout.len() <= 65536, "EVERY intermediate bounded");
        decoded(out)
    }
    fn compose_parts(&self, parts: &[Value]) -> Value {
        parts[1..]
            .iter()
            .fold(parts[0].clone(), |a, b| self.compose(&a, b))
    }
}
