#[derive(Clone, Debug)]
enum Tree {
    Leaf(usize),
    Branch(Box<Tree>, Box<Tree>),
}
fn trees(start: usize, count: usize) -> Vec<Tree> {
    if count == 1 {
        return vec![Tree::Leaf(start)];
    }
    let mut out = Vec::new();
    for left in 1..count {
        for a in trees(start, left) {
            for b in trees(start + left, count - left) {
                out.push(Tree::Branch(Box::new(a.clone()), Box::new(b)));
            }
        }
    }
    out
}
fn permutations(values: &mut [usize], at: usize, out: &mut Vec<Vec<usize>>) {
    if at == values.len() {
        out.push(values.to_vec());
        return;
    }
    for i in at..values.len() {
        values.swap(at, i);
        permutations(values, at + 1, out);
        values.swap(at, i);
    }
}
fn evaluate_tree(
    p: &Probe,
    tree: &Tree,
    order: &[usize],
    parts: &[Value],
    calls: &mut usize,
) -> Value {
    match tree {
        Tree::Leaf(i) => parts[order[*i]].clone(),
        Tree::Branch(a, b) => {
            let left = evaluate_tree(p, a, order, parts, calls);
            let right = evaluate_tree(p, b, order, parts, calls);
            *calls += 1;
            p.compose(&left, &right)
        }
    }
}
