// ORIGINAL literal-tree node/field/list edges, not selected-subtree counts.
fn inventory(value: &Value) -> (usize, usize, usize) {
    let mut out = (1, 0, 0);
    let children: Vec<&Value> = match value {
        Value::Object(fields) => {
            out.1 = fields.len();
            fields.values().collect()
        }
        Value::Array(items) => {
            out.2 = items.len();
            items.iter().collect()
        }
        _ => Vec::new(),
    };
    for child in children {
        let (n, f, i) = inventory(child);
        out.0 += n;
        out.1 += f;
        out.2 += i;
    }
    out
}
fn containers(value: &Value) -> usize {
    match value {
        Value::Object(fields) => 1 + fields.values().map(containers).sum::<usize>(),
        Value::Array(items) => 1 + items.iter().map(containers).sum::<usize>(),
        _ => 0,
    }
}
fn shallow(value: &Value, groups: usize) -> usize {
    match value {
        Value::Object(fields) => 3 + fields.len() + groups * (1 + 2 * fields.len()),
        Value::Array(_) => 4,
        _ => 3,
    }
}
fn full(value: &Value, groups: usize) -> usize {
    match value {
        Value::Object(fields) => {
            4 + fields.len()
                + groups * (1 + 2 * fields.len())
                + fields
                    .values()
                    .map(|v| shallow(v, groups) + full(v, groups) + containers(v))
                    .sum::<usize>()
        }
        Value::Array(items) => {
            5 + items.len()
                + items
                    .iter()
                    .map(|v| full(v, groups) + containers(v))
                    .sum::<usize>()
        }
        _ => 3,
    }
}
fn copies(value: &Value) -> usize {
    match value {
        Value::Object(fields) => fields.iter().map(|(k, v)| k.len() + copies(v)).sum(),
        Value::Array(items) => items.iter().map(copies).sum(),
        Value::String(s) => s.len(),
        _ => 0,
    }
}
