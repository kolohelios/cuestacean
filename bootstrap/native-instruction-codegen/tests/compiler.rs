type TestResult = Result<(), Box<dyn std::error::Error>>;
const POLICY: &str = include_str!(concat!(env!("CUESTACEAN_BOOTSTRAP_JSON"), "/lowering.json"));
const INPUT: &str = r#"{"formatVersion":1,"rules":{"z":{"result":{"op":"sum","left":{"op":"int"},"right":{"op":"bool"}}},"a\"\\\n雪":{"result":{"op":"text","field":"q\"\\\n雪"}},"m":{"result":{"op":"boolean","value":true}}}}"#;
// Transcribed from the documented module contract, never from compiler output.
const HEADER: &str = "\
// Generated by bootstrap-codegen. Do not edit by hand.\n\
use bootstrap_executor::{Error, runtime};\n\
use serde_json::Value;\n\n\
pub fn execute(input: &str) -> Result<i64, Error> {\n\
let mut _context = runtime::EvaluationContext::default();\n\
runtime::concrete(evaluate(&runtime::program(input)?, &mut _context)?)\n\
}\n\n\
pub fn execute_json(input: &str) -> Result<Value, Error> {\n\
let mut _context = runtime::EvaluationContext::default();\n\
runtime::concrete_json(evaluate(&runtime::program(input)?, &mut _context)?)\n\
}\n\n\
fn evaluate(node: &Value, _context: &mut runtime::EvaluationContext) -> Result<runtime::Value, Error> {\n\
_context.visit(|_context| evaluate_node(node, _context))\n\
}\n\n\
fn evaluate_node(node: &Value, _context: &mut runtime::EvaluationContext) -> Result<runtime::Value, Error> {\n\
match runtime::kind(node)? {\n";
#[cfg(feature = "compiled-lowering")]
const SUM: &str =
    "runtime::sum((Ok::<_, Error>(runtime::Value::Int))?, (Ok::<_, Error>(runtime::Value::Bool))?)";
const ARMS: &str = "\"a\\\"\\\\\\n雪\" => runtime::text(node, \"q\\\"\\\\\\n雪\"),\n\"m\" => Ok::<_, Error>(runtime::Value::Boolean(true)),\n\"z\" => runtime::sum((Ok::<_, Error>(runtime::Value::Int))?, (Ok::<_, Error>(runtime::Value::Bool))?),\n";
const FOOTER: &str = "kind => Err(Error::MissingRule { kind: kind.to_string() }),\n}\n}\n";
const CUSTOM: &str = r#"{"formatVersion":1,"cases":{"int":{"op":"text","value":"I"},"bool":{"op":"text","value":"B"},"sum":{"op":"concat","parts":[{"op":"lower","field":"right"},{"op":"text","value":":"},{"op":"lower","field":"left"}]},"text":{"op":"string","field":"field"},"boolean":{"op":"boolean","field":"value"}},"module":[{"op":"text","value":"BEGIN\n"},{"op":"lastRule"},{"op":"whileRules","body":[{"op":"kind"},{"op":"text","value":"="},{"op":"expression"},{"op":"text","value":";\n"},{"op":"previousRule"}]},{"op":"text","value":"END\n"}]}"#;
const CUSTOM_SOURCE: &str =
    "BEGIN\n\"z\"=B:I;\n\"m\"=true;\n\"a\\\"\\\\\\n雪\"=\"q\\\"\\\\\\n雪\";\nEND\n";
const EMPTY: &str =
    r#"{"formatVersion":1,"cases":{"null":{"op":"text","value":"unused"}},"module":[]}"#;
const MISSING_MODULE: &str =
    r#"{"formatVersion":1,"cases":{"null":{"op":"text","value":"unused"}}}"#;
const CURSOR: &str = r#"{"formatVersion":1,"cases":{"null":{"op":"text","value":"unused"}},"module":[{"op":"text","value":"NEVER PRINT PARTIAL SOURCE"},{"op":"nextRule"}]}"#;
const INVALID_PATH: &str =
    r#"{"formatVersion":1,"cases":{"null":{"op":"path","value":"bad-path!"}},"module":[]}"#;

fn expected() -> String {
    [HEADER, ARMS, FOOTER].concat()
}

#[test]
fn entire_default_reference_and_distinct_reverse_custom_source() -> TestResult {
    assert_eq!(generate(INPUT)?, expected());
    assert_eq!(generate_with_policy(INPUT, POLICY)?, expected());
    assert_eq!(generate_with_policy(INPUT, CUSTOM)?, CUSTOM_SOURCE);
    // Input storage order is not the traversal order; expected arms stay independent.
    let reordered = r#"{"rules":{"m":{"result":{"value":true,"op":"boolean"}},"a\"\\\n雪":{"result":{"field":"q\"\\\n雪","op":"text"}},"z":{"result":{"right":{"op":"bool"},"op":"sum","left":{"op":"int"}}}},"formatVersion":1}"#;
    assert_eq!(generate(reordered)?, expected());
    assert_eq!(generate_with_policy(reordered, CUSTOM)?, CUSTOM_SOURCE);
    assert_eq!(generate_with_policy(INPUT, EMPTY)?, "");
    Ok(())
}

fn json_failure(input: &str, policy: &str, diagnostic: &str) {
    let error = generate_with_policy(input, policy).expect_err("original typed decoding");
    match &error {
        Error::Json { document, source } => {
            assert_eq!(*document, "rules");
            assert!(source.to_string().contains(diagnostic), "{source}");
            assert_eq!(error.to_string(), format!("invalid rules JSON: {source}"));
            assert!(
                error
                    .source()
                    .expect("concrete JSON source")
                    .is::<serde_json::Error>()
            );
        }
        other => panic!("expected rules Json phase, got {other:?}"),
    }
}

fn lowering_failure(policy: &str, diagnostic: &str) {
    let error = generate_with_policy(INPUT, policy).expect_err("policy or assembly failure");
    match &error {
        Error::Lowering {
            source: lowering::Error::Invalid { reason },
        } => {
            assert_eq!(reason, diagnostic);
            assert_eq!(error.to_string(), format!("lowering: {diagnostic}"));
            assert!(
                error
                    .source()
                    .expect("concrete lowering source")
                    .is::<lowering::Error>()
            );
        }
        other => panic!("expected Lowering/Invalid phase, got {other:?}"),
    }
}

#[test]
fn real_error_sources_typed_version_policy_and_assembly_precedence() -> TestResult {
    for policy in ["!", EMPTY] {
        for (input, diagnostic) in [
            ("!", "expected value"),
            ("{}", "missing field `formatVersion`"),
            (
                r#"{"formatVersion":2,"rules":{"ignored":{"result":{"op":"boolean","value":0}}}}"#,
                "invalid type: integer `0`, expected a boolean",
            ),
            (
                r#"{"formatVersion":1,"rules":{"x":{"result":{"op":"null","extra":0}}}}"#,
                "unknown field `extra`",
            ),
            (
                r#"{"formatVersion":1,"rules":{"x":{"result":{"op":"boolean","value":0}},"x":{"result":{"op":"null"}}}}"#,
                "invalid type: integer `0`, expected a boolean",
            ),
            (
                r#"{"formatVersion":1,"formatVersion":1,"rules":{}}"#,
                "duplicate field `formatVersion`",
            ),
        ] {
            json_failure(input, policy, diagnostic);
            assert_eq!(generate(INPUT)?, expected());
        }
        for version in [0, 2, u32::MAX] {
            let input = format!(r#"{{"formatVersion":{version},"rules":{{}}}}"#);
            let error = generate_with_policy(&input, policy).expect_err("version before policy");
            assert!(
                matches!(&error, Error::Version { document: "rules", version: actual } if *actual == version)
            );
            assert_eq!(
                error.to_string(),
                format!("unsupported rules formatVersion: {version}")
            );
            assert!(error.source().is_none());
            assert_eq!(generate_with_policy(INPUT, CUSTOM)?, CUSTOM_SOURCE);
        }
    }
    let error = generate_with_policy(INPUT, "!").expect_err("policy JSON phase");
    match &error {
        Error::Lowering {
            source: lowering::Error::Json { source },
        } => {
            assert_eq!(source.classify(), serde_json::error::Category::Syntax);
            assert_eq!(source.to_string(), "expected value at line 1 column 1");
            assert_eq!(
                error.to_string(),
                "invalid lowering policy JSON: expected value at line 1 column 1"
            );
            assert!(
                error
                    .source()
                    .expect("lowering")
                    .source()
                    .expect("JSON")
                    .is::<serde_json::Error>()
            );
        }
        other => panic!("expected nested policy JSON source, got {other:?}"),
    }
    for (policy, reason) in [
        (INVALID_PATH, "invalid Rust path"),
        (MISSING_MODULE, "missing module program"),
        (CURSOR, "no current rule"),
        (
            r#"{"formatVersion":2,"cases":{"null":{"op":"text","value":"x"}},"module":[]}"#,
            "formatVersion 1 required",
        ),
    ] {
        lowering_failure(policy, reason);
        assert_eq!(generate_with_policy(INPUT, CUSTOM)?, CUSTOM_SOURCE);
    }
    let oversize = json!({"formatVersion":1,"cases":{"null":{"op":"text","value":"x"}},"module":[{"op":"text","value":"x".repeat(65537)}]}).to_string();
    lowering_failure(&oversize, "module text exceeds 64 KiB");
    assert_eq!(generate(INPUT)?, expected());
    Ok(())
}

static NEXT_DIR: AtomicU64 = AtomicU64::new(0);
struct Cli {
    root: PathBuf,
    binary: PathBuf,
}
impl Cli {
    fn new() -> Result<Self, Box<dyn std::error::Error>> {
        use std::os::unix::fs::PermissionsExt;
        let binary = PathBuf::from(env!("CARGO_BIN_EXE_bootstrap-codegen"));
        assert!(binary.is_absolute());
        let metadata = fs::metadata(&binary)?;
        assert!(metadata.is_file());
        fs::File::open(&binary)?;
        assert_ne!(metadata.permissions().mode() & 0o111, 0);
        let root = std::env::temp_dir().join(format!(
            "native-instruction-cli-{}-{}",
            std::process::id(),
            NEXT_DIR.fetch_add(1, Ordering::Relaxed)
        ));
        assert!(root.is_absolute());
        fs::create_dir(&root)?;
        fs::create_dir(root.join("home"))?;
        Ok(Self { root, binary })
    }
    fn file(&self, name: &str, body: &str) -> Result<PathBuf, std::io::Error> {
        let path = self.root.join(name);
        fs::write(&path, body)?;
        Ok(path)
    }
    fn run(&self, args: &[&Path]) -> Output {
        Command::new(&self.binary)
            .args(args)
            .env_clear()
            .env("HOME", self.root.join("home"))
            .env("PATH", self.root.join("unusable-path"))
            .current_dir(&self.root)
            .output()
            .expect("launch actual Cargo CLI; setup failure is not a semantic negative")
    }
    fn success(&self, args: &[&Path], expected: &str) {
        let output = self.run(args);
        assert!(output.status.success(), "{output:?}");
        assert!(output.stderr.is_empty(), "{output:?}");
        assert_eq!(output.stdout, expected.as_bytes());
    }
    fn failure(&self, args: &[&Path], diagnostic: &str) {
        let output = self.run(args);
        assert_eq!(output.status.code(), Some(2), "{output:?}");
        assert!(output.stdout.is_empty(), "{output:?}");
        assert_eq!(output.stderr, format!("{diagnostic}\n").as_bytes());
    }
    fn read_failure(&self, args: &[&Path], path: &Path) {
        let output = self.run(args);
        assert_eq!(output.status.code(), Some(2), "{output:?}");
        assert!(output.stdout.is_empty(), "{output:?}");
        let stderr = String::from_utf8(output.stderr).expect("UTF-8 read diagnostic");
        let prefix = format!("cannot read {}: ", path.display());
        let suffix = stderr
            .strip_prefix(&prefix)
            .expect("exact failed path and read phase");
        assert!(suffix.ends_with('\n'));
        assert!(
            !suffix.trim().is_empty(),
            "OS error suffix must not be empty"
        );
    }
}
impl Drop for Cli {
    fn drop(&mut self) {
        fs::remove_dir_all(&self.root).expect("remove owned CLI directory");
    }
}

#[test]
fn actual_cli_exact_usage_read_typed_version_policy_assembly_and_recovery() -> TestResult {
    let cli = Cli::new()?;
    let good = cli.file("rules.json", INPUT)?;
    let custom = cli.file("custom.json", CUSTOM)?;
    let canonical = cli.file("canonical.json", POLICY)?;
    let malformed = cli.file("malformed.json", "!")?;
    let typed = cli.file("typed.json", "{}")?;
    let version = cli.file("version.json", r#"{"formatVersion":2,"rules":{}}"#)?;
    let path = cli.file("path.json", INVALID_PATH)?;
    let cursor = cli.file("cursor.json", CURSOR)?;
    let absent_module = cli.file("absent-module.json", MISSING_MODULE)?;
    let empty = cli.file("empty.json", EMPTY)?;
    let policy_version = cli.file(
        "policy-version.json",
        r#"{"formatVersion":2,"cases":{"null":{"op":"text","value":"x"}},"module":[]}"#,
    )?;
    let missing = cli.root.join("missing.json");
    let directory = cli.root.join("directory.json");
    fs::create_dir(&directory)?;
    cli.success(&[&good], &expected());
    cli.success(&[&good, &canonical], &expected());
    cli.success(&[&good, &custom], CUSTOM_SOURCE);
    cli.success(&[&good, &empty], "");
    for (args, diagnostic) in [
        (
            vec![],
            "usage: bootstrap-codegen <rules.json> [lowering.json]",
        ),
        (
            vec![good.as_path(), custom.as_path(), missing.as_path()],
            "usage: bootstrap-codegen <rules.json> [lowering.json]",
        ),
        (
            vec![malformed.as_path()],
            "invalid rules JSON: expected value at line 1 column 1",
        ),
        (
            vec![typed.as_path()],
            "invalid rules JSON: missing field `formatVersion` at line 1 column 2",
        ),
        (
            vec![typed.as_path(), malformed.as_path()],
            "invalid rules JSON: missing field `formatVersion` at line 1 column 2",
        ),
        (
            vec![version.as_path(), malformed.as_path()],
            "unsupported rules formatVersion: 2",
        ),
        (
            vec![good.as_path(), malformed.as_path()],
            "invalid lowering policy JSON: expected value at line 1 column 1",
        ),
        (
            vec![good.as_path(), policy_version.as_path()],
            "lowering: formatVersion 1 required",
        ),
        (
            vec![good.as_path(), path.as_path()],
            "lowering: invalid Rust path",
        ),
        (
            vec![good.as_path(), absent_module.as_path()],
            "lowering: missing module program",
        ),
        (
            vec![good.as_path(), cursor.as_path()],
            "lowering: no current rule",
        ),
    ] {
        cli.failure(&args, diagnostic);
        cli.success(&[&good, &custom], CUSTOM_SOURCE);
    }
    for (args, failed_path) in [
        (
            vec![missing.as_path(), malformed.as_path()],
            missing.as_path(),
        ),
        (vec![directory.as_path()], directory.as_path()),
        (vec![good.as_path(), missing.as_path()], missing.as_path()),
        (
            vec![good.as_path(), directory.as_path()],
            directory.as_path(),
        ),
        // Explicit policy read happens BEFORE the API sees malformed/typed rules.
        (
            vec![malformed.as_path(), missing.as_path()],
            missing.as_path(),
        ),
        (
            vec![typed.as_path(), directory.as_path()],
            directory.as_path(),
        ),
    ] {
        cli.read_failure(&args, failed_path);
        cli.success(&[&good], &expected());
    }
    Ok(())
}

#[cfg(feature = "compiled-lowering")]
#[test]
fn both_fresh_actual_drivers_independent_success_error_recovery() -> TestResult {
    use bootstrap_executor::{compiled_lowering, compiled_meta_lowering, module};
    let instruction = json!({"op":"sum","left":{"op":"int"},"right":{"op":"bool"}});
    assert_eq!(
        lowering::Context::run(&instruction, &compiled_lowering::Compiled)?,
        SUM
    );
    let error = lowering::Context::run(
        &json!({"op":"unknownTestKind"}),
        &compiled_lowering::Compiled,
    )
    .expect_err("real compiled instruction dispatch error");
    assert!(
        matches!(&error, lowering::Error::Invalid { reason } if reason == "missing lowering case for \"unknownTestKind\"")
    );
    assert_eq!(
        error.to_string(),
        "lowering: missing lowering case for \"unknownTestKind\""
    );
    assert_eq!(
        lowering::Context::run(&instruction, &compiled_lowering::Compiled)?,
        SUM
    );
    let projected = vec![
        (
            "a\"\\\n雪".to_owned(),
            json!({"op":"text","field":"q\"\\\n雪"}),
        ),
        ("m".to_owned(), json!({"op":"boolean","value":true})),
        ("z".to_owned(), instruction),
    ];
    assert_eq!(
        module::Frame::run(&projected, &compiled_lowering::Compiled)?,
        expected()
    );
    let oversized_kind = vec![("x".repeat(65537), json!({"op":"int"}))];
    let error = module::Frame::run(&oversized_kind, &compiled_lowering::Compiled)
        .expect_err("actual compiled assembly rejects oversized quoted key");
    assert_eq!(error.to_string(), "lowering: rule kind exceeds 64 KiB");
    assert_eq!(
        module::Frame::run(&projected, &compiled_lowering::Compiled)?,
        expected()
    );
    let meta =
        json!({"op":"selectCase","tag":"leaf\"雪","value":{"op":"text","value":"quote\"\n雪"}});
    let meta_expected = "\"leaf\\\"雪\" => ctx.text(\"quote\\\"\\n雪\"), ";
    assert_eq!(
        lowering::Context::run(&meta, &compiled_meta_lowering::Compiled)?,
        meta_expected
    );
    let error = lowering::Context::run(
        &json!({"op":"selectCase","tag":false}),
        &compiled_meta_lowering::Compiled,
    )
    .expect_err("real compiled meta string projection error");
    assert!(
        matches!(&error, lowering::Error::Invalid { reason } if reason == "field \"tag\" must be a string")
    );
    assert_eq!(
        error.to_string(),
        "lowering: field \"tag\" must be a string"
    );
    assert_eq!(
        lowering::Context::run(&meta, &compiled_meta_lowering::Compiled)?,
        meta_expected
    );
    Ok(())
}
