type TestResult = Result<(), Box<dyn std::error::Error>>;
const CLI: &str = env!("CARGO_BIN_EXE_bootstrap-scan-codegen");
const STEP: &str = "cursor.step()?;\n";
fn program(body: Value) -> String {
    json!({"formatVersion":1,"body":body}).to_string()
}
fn policy(cases: Value) -> String {
    json!({"formatVersion":1,"cases":cases}).to_string()
}
fn rust(body: &str, mutable: bool) -> String {
    format!(
        "// Generated by bootstrap-scan-codegen. Do not edit by hand.\nuse crate::scanner::{{Cursor, Error, Scan}};\npub fn scan(source: &str, offset: usize) -> Result<Scan, Error> {{\nlet {}cursor = Cursor::new(source, offset)?;\n{body}Ok(cursor.finish())\n}}\n",
        if mutable { "mut " } else { "" }
    )
}
#[test]
fn complete_source_branch_patterns_and_flow() -> TestResult {
    assert_eq!(scanner::generate(&program(json!([])))?, rust("", false));
    let same = json!([{"op":"setFlag","value":true}]);
    assert_eq!(
        scanner::generate(&program(
            json!([{"op":"if","condition":{"op":"hasByte"},"then":same,"else":same}])
        ))?,
        rust(&format!("{STEP}{STEP}cursor.set_flag(true);\n"), true)
    );
    // Empty then chooses inversion, propagating De Morgan to ordered children.
    let input = program(
        json!([{"op":"if","condition":{"op":"and","left":{"op":"byteIn","ahead":2,"bytes":[99,97,98,97]},"right":{"op":"flagIs","value":false}},"then":[],"else":[{"op":"advanceChar"}]}]),
    );
    assert_eq!(
        scanner::generate(&input)?,
        rust(
            &format!(
                "{STEP}if (!matches!(cursor.peek_at(2), Some(97..=99))) || (cursor.flag()) {{\n{STEP}cursor.advance_char()?;\n}}\n"
            ),
            true
        )
    );
    let input = program(
        json!([{"op":"if","condition":{"op":"charIn","characters":["λ","'","\n","λ"]},"then":[{"op":"reject","reason":"\"\\\n雪"}],"else":[]}]),
    );
    assert_eq!(
        scanner::generate(&input)?,
        rust(
            &format!(
                "{STEP}if matches!(cursor.peek_char(), Some('\\n' | '\\'' | 'λ')) {{\n{STEP}cursor.reject(\"\\\"\\\\\\n雪\")?;\n}}\n"
            ),
            true
        )
    );
    // Both loops become once-blocks; each break targets its nearest block.
    let input = program(
        json!([{"op":"repeat","count":3,"body":[{"op":"repeat","count":1,"body":[{"op":"break"}]},{"op":"break"},{"op":"advance"}]}]),
    );
    assert_eq!(
        scanner::generate(&input)?,
        rust(
            &format!(
                "{STEP}'scan0: {{\n{STEP}{STEP}'scan1: {{\n{STEP}{STEP}break 'scan1;\n}}\n{STEP}break 'scan0;\n}}\n"
            ),
            true
        )
    );
    let input = program(
        json!([{"op":"repeat","count":0,"body":[{"op":"advance"}]},{"op":"repeat","count":2,"body":[{"op":"setFlag","value":true}]},{"op":"while","condition":{"op":"hasByte"},"body":[{"op":"break"}]}]),
    );
    assert_eq!(
        scanner::generate(&input)?,
        rust(
            &format!(
                "{STEP}{STEP}for _ in 0..2 {{\n{STEP}{STEP}cursor.set_flag(true);\n}}\n{STEP}if cursor.peek().is_some() {{\n'scan0: {{\n{STEP}break 'scan0;\n}}\n}}\n"
            ),
            true
        )
    );
    Ok(())
}
#[test]
fn interpreter_cursor_unicode_errors_and_exact_fuel() -> TestResult {
    let input = program(json!([{"op":"advanceChar"},{"op":"setFlag","value":true}]));
    assert_eq!(
        scanner::interpret(&input, "xλ雪", 1)?,
        scanner::Scan {
            offset: 3,
            flag: true
        }
    );
    assert!(matches!(
        scanner::interpret(&input, "λ", 1),
        Err(scanner::Error::Offset)
    ));
    assert!(matches!(
        scanner::interpret(&input, "", 0),
        Err(scanner::Error::AdvanceChar)
    ));
    let ascii = program(json!([{"op":"advance"}]));
    for source in ["", "λ"] {
        assert!(matches!(
            scanner::interpret(&ascii, source, 0),
            Err(scanner::Error::Advance)
        ));
    }
    let rejection = program(json!([{"op":"advanceChar"},{"op":"reject","reason":"stop"}]));
    assert!(
        matches!(scanner::interpret(&rejection, "λ!", 0), Err(scanner::Error::Rejected { offset: 2, reason }) if reason == "stop")
    );
    let mut cursor = scanner::Cursor::new("λ", 0)?;
    assert_eq!(cursor.peek_at(usize::MAX), None);
    assert_eq!(cursor.peek_char(), Some('λ'));
    cursor.advance_char()?;
    assert_eq!(
        cursor.finish(),
        scanner::Scan {
            offset: 2,
            flag: false
        }
    );
    assert!(matches!(
        scanner::Cursor::new("", 1),
        Err(scanner::Error::Offset)
    ));
    // At empty source fuel is 128: repeat entry + 63*(iteration+action)=127.
    let mut body = json!([{"op":"repeat","count":63,"body":[{"op":"setFlag","value":true}]},{"op":"setFlag","value":false}]);
    assert_eq!(
        scanner::interpret(&program(body.clone()), "", 0)?,
        scanner::Scan {
            offset: 0,
            flag: false
        }
    );
    body.as_array_mut()
        .ok_or("body array")?
        .push(json!({"op":"setFlag","value":true}));
    assert!(matches!(
        scanner::interpret(&program(body), "", 0),
        Err(scanner::Error::Budget)
    ));
    let spin = program(json!([{"op":"while","condition":{"op":"flagIs","value":false},"body":[]}]));
    assert!(matches!(
        scanner::interpret(&spin, "", 0),
        Err(scanner::Error::Budget)
    ));
    let nearest = program(
        json!([{"op":"repeat","count":2,"body":[{"op":"repeat","count":2,"body":[{"op":"break"}]},{"op":"advanceChar"}]}]),
    );
    assert_eq!(
        scanner::interpret(&nearest, "λ雪!", 0)?,
        scanner::Scan {
            offset: 5,
            flag: false
        }
    );
    Ok(())
}
#[test]
fn eager_typed_validation_custom_policy_and_recovery() -> TestResult {
    let bad = [
        (
            program(json!([{"op":"break"}])),
            "break requires an enclosing loop",
        ),
        (
            program(json!([{"op":"repeat","count":0,"body":[{"op":"reject","reason":""}]}])),
            "reject requires a nonempty reason",
        ),
        (
            program(
                json!([{"op":"if","condition":{"op":"hasByte"},"then":[],"else":[{"op":"break"}]}]),
            ),
            "break requires an enclosing loop",
        ),
        (
            program(json!([{"op":"repeat","count":1,"body":[{"op":"break"}]},{"op":"break"}])),
            "break requires an enclosing loop",
        ),
        (
            program(json!([{"op":"repeat","count":65,"body":[]}])),
            "repeat count exceeds 64",
        ),
    ];
    for (input, reason) in bad {
        for result in [
            scanner::generate(&input),
            scanner::generate_with_policy(&input, "{"),
        ] {
            assert!(matches!(result, Err(scanner::Error::Program { reason: r }) if r == reason));
        }
        assert!(
            matches!(scanner::interpret(&input, "λ", 1), Err(scanner::Error::Program { reason: r }) if r == reason)
        );
    }
    for input in [
        "{",
        r#"{"formatVersion":1,"body":[],"body":[]}"#,
        r#"{"formatVersion":1,"body":[{"op":"advance","op":"break"}]}"#,
    ] {
        assert!(matches!(
            scanner::generate_with_policy(input, "{"),
            Err(scanner::Error::Json { .. })
        ));
    }
    let empty = program(json!([]));
    let custom = policy(json!({"program":{"op":"text","value":"independent custom output\n"}}));
    assert_eq!(
        scanner::generate_with_policy(&empty, &custom)?,
        "independent custom output\n"
    );
    let missing = policy(json!({"other":{"op":"text","value":"wrong"}}));
    assert!(matches!(
        scanner::generate_with_policy(&empty, &missing),
        Err(scanner::Error::Lowering { .. })
    ));
    assert_eq!(scanner::generate(&empty)?, rust("", false));
    Ok(())
}

struct Sandbox(PathBuf);
impl Sandbox {
    fn new() -> Result<Self, std::io::Error> {
        let path =
            std::env::temp_dir().join(format!("scanner-compiler-evidence-{}", std::process::id()));
        fs::create_dir(&path)?;
        fs::create_dir(path.join("home"))?;
        Ok(Self(path))
    }
    fn cli(&self, args: &[&str]) -> Result<std::process::Output, Box<dyn std::error::Error>> {
        let binary = std::path::Path::new(CLI);
        assert!(binary.is_absolute());
        assert!(fs::metadata(binary)?.is_file());
        fs::File::open(binary)?;
        #[cfg(unix)]
        {
            use std::os::unix::fs::PermissionsExt;
            assert_ne!(fs::metadata(binary)?.permissions().mode() & 0o111, 0);
        }
        Ok(Command::new(binary)
            .current_dir(&self.0)
            .env_clear()
            .env("HOME", self.0.join("home"))
            .env("PATH", "/nonexistent")
            .args(args)
            .output()?)
    }
}
impl Drop for Sandbox {
    fn drop(&mut self) {
        let _ = fs::remove_dir_all(&self.0);
    }
}
#[test]
fn cli_exit_two_no_partial_rust_and_recovery() -> TestResult {
    let tmp = Sandbox::new()?;
    fs::write(tmp.0.join("valid.json"), program(json!([])))?;
    fs::write(
        tmp.0.join("bad.json"),
        program(
            json!([{"op":"repeat","count":0,"body":[{"op":"break"},{"op":"reject","reason":""}]}]),
        ),
    )?;
    fs::write(tmp.0.join("syntax.json"), "{")?;
    fs::write(
        tmp.0.join("duplicate.json"),
        r#"{"formatVersion":1,"body":[],"body":[]}"#,
    )?;
    fs::write(tmp.0.join("policy.json"), "{")?;
    fs::write(
        tmp.0.join("custom.json"),
        policy(json!({"program":{"op":"text","value":"custom\n"}})),
    )?;
    for (args, reason) in [
        (vec![], "usage:"),
        (vec!["valid.json", "custom.json", "extra"], "usage:"),
        (vec!["absent.json"], "cannot read"),
        (vec!["syntax.json"], "invalid scanner JSON"),
        (vec!["duplicate.json"], "duplicate field"),
        (
            vec!["bad.json", "policy.json"],
            "reject requires a nonempty reason",
        ),
        (
            vec!["valid.json", "policy.json"],
            "invalid lowering policy JSON",
        ),
    ] {
        let output = tmp.cli(&args)?;
        assert_eq!(output.status.code(), Some(2), "{args:?}");
        assert!(output.stdout.is_empty(), "{args:?}");
        assert!(
            String::from_utf8(output.stderr)?.contains(reason),
            "{args:?}: {reason}"
        );
        let recovered = tmp.cli(&["valid.json"])?;
        assert!(recovered.status.success());
        assert!(recovered.stderr.is_empty());
        assert_eq!(String::from_utf8(recovered.stdout)?, rust("", false));
    }
    let output = tmp.cli(&["valid.json", "custom.json"])?;
    assert!(output.status.success());
    assert!(output.stderr.is_empty());
    assert_eq!(output.stdout, b"custom\n");
    Ok(())
}

#[cfg(feature = "compiled-lowering")]
#[test]
fn fresh_compiled_scan_meta_drivers_execute_real_context() -> TestResult {
    use bootstrap_executor::{compiled_meta_lowering, compiled_scan_lowering};
    assert_eq!(
        lowering::Context::run(
            &json!({"op":"advanceChar"}),
            &compiled_scan_lowering::Compiled
        )?,
        "cursor.step()?;\ncursor.advance_char()?;\n"
    );
    assert_eq!(
        lowering::Context::run(
            &json!({"op":"byteIn","ahead":0,"inverse":false,"bytes":[122,120,121,120]}),
            &compiled_scan_lowering::Compiled
        )?,
        "matches!(cursor.peek(), Some(120..=122))"
    );
    assert_eq!(
        lowering::Context::run(
            &json!({"op":"text","value":"hello λ"}),
            &compiled_meta_lowering::Compiled
        )?,
        "ctx.text(\"hello λ\")"
    );
    assert!(
        lowering::Context::run(&json!({"op":"absent"}), &compiled_scan_lowering::Compiled).is_err()
    );
    assert!(
        lowering::Context::run(
            &json!({"op":"byteIn","ahead":0,"inverse":false,"bytes":[255]}),
            &compiled_scan_lowering::Compiled
        )
        .is_err()
    );
    Ok(())
}

#[cfg(feature = "source")]
#[test]
fn all_twenty_seven_fresh_lexical_wrappers() -> TestResult {
    type Wrapper = fn(&str, usize) -> Result<scanner::Scan, scanner::Error>;
    // The PROGRAM specifications used to generate these wrappers are Go-backed
    // verification inputs. They never feed native compiler construction.
    let cases: [(Wrapper, &str, usize, bool); 27] = [
        (scanner::whitespace, " \t//λ\n!", 7, true),
        (scanner::decimal, "-12!", 3, true),
        (scanner::integer_literal, "0xAf!", 4, false),
        (scanner::identifier, "abc_9λ", 5, true),
        (scanner::after_operand, " \t", 2, false),
        (scanner::after_word_operator, " \t", 2, false),
        (scanner::group_open, "(!", 1, true),
        (scanner::call_open, " (!", 2, true),
        (scanner::group_close, " )!", 2, false),
        (scanner::list_open, "[!", 1, true),
        (scanner::list_close, "]!", 1, true),
        (scanner::index_close, " ]!", 2, false),
        (scanner::list_tail, "]!", 1, true),
        (scanner::record_close, "}!", 1, true),
        (scanner::record_colon, ":!", 1, false),
        (scanner::record_label, "\"λ\"", 0, true),
        (scanner::selector_identifier, "x9λ", 2, true),
        (scanner::selector_open, ".!", 1, true),
        (scanner::slice_separator, ":!", 1, true),
        (scanner::conjunction_open, "[!", 1, false),
        (scanner::record_open, "{!", 1, false),
        (scanner::record_tail, "}!", 1, true),
        (scanner::bound_prefix, ">=!", 2, true),
        (scanner::infix, "div!", 3, true),
        (scanner::negation_prefix, "-λ", 1, true),
        (scanner::not_prefix, "!λ", 1, true),
        (scanner::string_literal, "\"λ\"!", 4, true),
    ];
    for (index, (scan, source, offset, flag)) in cases.into_iter().enumerate() {
        assert_eq!(
            scan(source, 0)?,
            scanner::Scan { offset, flag },
            "wrapper {index}"
        );
        let shifted = format!("雪{source}");
        assert_eq!(
            scan(&shifted, 3)?,
            scanner::Scan {
                offset: offset + 3,
                flag
            },
            "shifted wrapper {index}"
        );
        assert!(
            matches!(scan("λ", 1), Err(scanner::Error::Offset)),
            "wrapper {index}"
        );
        assert!(
            matches!(scan("", 1), Err(scanner::Error::Offset)),
            "wrapper {index}"
        );
    }
    for (scan, reason) in [
        (
            scanner::call_open as Wrapper,
            "expected opening parenthesis",
        ),
        (scanner::group_close, "expected closing parenthesis"),
        (scanner::index_close, "expected closing bracket"),
        (scanner::list_tail, "expected comma or closing bracket"),
        (scanner::record_colon, "expected colon"),
        (scanner::record_label, "expected quoted record label"),
        (scanner::selector_identifier, "expected selector label"),
        (scanner::conjunction_open, "expected opening bracket"),
        (scanner::record_tail, "expected comma or closing brace"),
        (scanner::record_open, "expected opening brace"),
        (scanner::decimal, "expected signed decimal integer"),
        (scanner::integer_literal, "expected signed decimal integer"),
    ] {
        for source in ["", "λ"] {
            assert!(
                matches!(scan(source, 0), Err(scanner::Error::Rejected { offset: 0, reason: r }) if r == reason)
            );
        }
    }
    // The other fifteen scanners succeed without consuming at EOF, flag false.
    for scan in [
        scanner::whitespace as Wrapper,
        scanner::after_operand,
        scanner::after_word_operator,
        scanner::identifier,
        scanner::group_open,
        scanner::list_open,
        scanner::list_close,
        scanner::record_close,
        scanner::selector_open,
        scanner::slice_separator,
        scanner::bound_prefix,
        scanner::infix,
        scanner::negation_prefix,
        scanner::not_prefix,
        scanner::string_literal,
    ] {
        assert_eq!(
            scan("λ", 2)?,
            scanner::Scan {
                offset: 2,
                flag: false
            }
        );
    }
    assert!(matches!(
        scanner::after_operand("\nλ", 0),
        Err(scanner::Error::Rejected { offset: 1, .. })
    ));
    assert!(
        matches!(scanner::call_open("\n(", 0), Err(scanner::Error::Rejected { offset: 1, reason }) if reason == "newline after call name")
    );
    Ok(())
}
