//! Independent compiler evidence; no runtime execution API or captured sources.
use bootstrap_executor::{lowering, unification};
use serde_json::{Value, json};
use std::{fs, path::Path, process::Command};

type TestResult = Result<(), Box<dyn std::error::Error>>;
const CLI: &str = env!("CARGO_BIN_EXE_bootstrap-unify-codegen");
const NATIVE_POLICY: &str = include_str!(concat!(
    env!("CUESTACEAN_BOOTSTRAP_JSON"),
    "/unify-lowering.json"
));
fn control(function: Option<&str>, result: Value) -> String {
    let mut program = json!({"formatVersion":1,"result":result});
    if let Some(name) = function {
        program["function"] = json!(name);
    }
    program.to_string()
}
fn policy(cases: Value) -> String {
    json!({"formatVersion":1,"cases":cases}).to_string()
}
fn source(name: &str, arguments: &str, body: &str) -> String {
    format!(
        "// Generated by bootstrap-unify-codegen. Do not edit by hand.\nuse crate::{{Error, runtime::Value}};\npub fn {name}({arguments}) -> Result<Value, Error> {{\n{body}\n}}\n"
    )
}
#[test]
fn complete_sources_pin_signatures_literals_and_layout() -> TestResult {
    let binary = "_left: Value, _right: Value";
    for (function, result, name, arguments, body) in [
        (
            None,
            json!({"op":"input","input":"right"}),
            "unify",
            binary,
            "Ok::<_, Error>(_right.clone())",
        ),
        (
            Some("logicalNot"),
            json!({"op":"fail","reason":"incompleteInt"}),
            "logical_not",
            "_left: Value",
            "Err(Error::Incomplete)",
        ),
        (
            Some("negate"),
            json!({"op":"integerPrimitive","operation":"negate"}),
            "negate",
            "_left: Value",
            "crate::runtime::integer_negate(&_left)",
        ),
        (
            Some("listSlice"),
            json!({"op":"listSlice"}),
            "list_slice",
            "_left: Value, _right: Value, _third: Value",
            "crate::runtime::list_slice_elements(&_left, &_right, &_third)",
        ),
        (
            Some("listSlice"),
            json!({"op":"input","input":"third"}),
            "list_slice",
            "_left: Value, _right: Value, _third: Value",
            "Ok::<_, Error>(_third.clone())",
        ),
        (
            Some("sum"),
            json!({"op":"integer","value":i64::MIN}),
            "sum",
            binary,
            "Ok::<_, Error>(Value::Integer(-9223372036854775808))",
        ),
        (
            Some("lowerBound"),
            json!({"op":"bounds","lower":{"op":"input","input":"left","endpoint":"lower"},"upper":{"op":"integer","value":i64::MAX}}),
            "lower_bound",
            "_left: Value",
            "Ok::<_, Error>(Value::Bounds { lower: (Ok::<_, Error>(crate::unification::endpoint(&_left, crate::unification::Endpoint::Lower)))?, upper: (Ok::<_, Error>(Some(9223372036854775807)))? })",
        ),
        (
            None,
            json!({"op":"if","condition":{"op":"same"},"then":{"op":"boolean","value":true},"else":{"op":"fail","reason":"types"}}),
            "unify",
            binary,
            "if (Ok::<_, Error>(_left == _right))? { Ok::<_, Error>(Value::Boolean(true)) } else { crate::unification::fail(crate::unification::Failure::Types, &_left, &_right) }",
        ),
        (
            None,
            json!({"op":"letBounds","lower":{"op":"empty"},"upper":{"op":"integer","value":7},"result":{"op":"bounds","lower":{"op":"local","endpoint":"upper"},"upper":{"op":"local","endpoint":"lower"}}}),
            "unify",
            binary,
            "{ let (_lower, _upper) = ((Ok::<_, Error>(None::<i64>))?, (Ok::<_, Error>(Some(7)))?); Ok::<_, Error>(Value::Bounds { lower: (Ok::<_, Error>(_upper))?, upper: (Ok::<_, Error>(_lower))? }) }",
        ),
    ] {
        let input = control(function, result);
        let expected = source(name, arguments, body);
        assert_eq!(unification::generate(&input)?, expected);
        assert_eq!(
            unification::generate_with_policy(&input, NATIVE_POLICY)?,
            expected
        );
    }
    Ok(())
}
#[test]
fn custom_policy_observes_typed_facts_and_changes_source() -> TestResult {
    // This policy derives its answer from the actual typed bridge, not fixtures.
    let observer = policy(json!({
        "program":{"op":"concat","parts":[{"op":"string","field":"function"},{"op":"boolean","field":"unary"},{"op":"boolean","field":"ternary"},{"op":"lower","field":"result"}]},
        "inputValue":{"op":"string","field":"input"},
        "unaryFail":{"op":"string","field":"reason"},
        "integerValue":{"op":"signed","field":"value"}
    }));
    for (function, result, expected) in [
        (
            None,
            json!({"op":"input","input":"left"}),
            "\"unify\"falsefalse\"left\"",
        ),
        (
            Some("logicalNot"),
            json!({"op":"fail","reason":"logical"}),
            "\"logicalNot\"truefalse\"logical\"",
        ),
        (
            Some("listSlice"),
            json!({"op":"input","input":"third"}),
            "\"listSlice\"falsetrue\"third\"",
        ),
        (
            Some("negate"),
            json!({"op":"integer","value":-17}),
            "\"negate\"truefalse-17",
        ),
    ] {
        assert_eq!(
            unification::generate_with_policy(&control(function, result), &observer)?,
            expected
        );
    }
    let input = control(None, json!({"op":"input","input":"left"}));
    let changed =
        policy(json!({"program":{"op":"text","value":"// deliberate custom compiler\n"}}));
    assert_eq!(
        unification::generate_with_policy(&input, &changed)?,
        "// deliberate custom compiler\n"
    );
    assert_ne!(
        unification::generate(&input)?,
        "// deliberate custom compiler\n"
    );
    assert!(matches!(
        unification::generate_with_policy(&input, "not JSON"),
        Err(unification::Error::Lowering { .. })
    ));
    assert_eq!(
        unification::generate_with_policy(&input, &observer)?,
        "\"unify\"falsefalse\"left\""
    );
    Ok(())
}
#[test]
fn validation_is_eager_and_precedes_policy_decoding() {
    let valid = json!({"op":"input","input":"left"});
    let dead = |bad| json!({"op":"if","condition":{"op":"kindIs","input":"left","kind":"null"},"then":valid,"else":bad});
    for (function, result, reason) in [
        (
            None,
            dead(json!({"op":"input","input":"third"})),
            "third input requires ternary control",
        ),
        (
            None,
            json!({"op":"listSlice"}),
            "listSlice requires ternary control",
        ),
        (
            Some("logicalNot"),
            dead(json!({"op":"input","input":"right"})),
            "unary control requires unary expressions",
        ),
        (
            Some("logicalNot"),
            json!({"op":"integerPrimitive","operation":"difference"}),
            "unary control requires unary expressions",
        ),
        (
            None,
            dead(
                json!({"op":"bounds","lower":{"op":"local","endpoint":"lower"},"upper":{"op":"empty"}}),
            ),
            "local endpoint outside letBounds",
        ),
        (
            None,
            json!({"op":"letBounds","lower":{"op":"local","endpoint":"upper"},"upper":{"op":"empty"},"result":valid}),
            "local endpoint outside letBounds",
        ),
        (
            None,
            json!({"op":"bounds","lower":{"op":"offset","value":{"op":"empty"},"delta":0},"upper":{"op":"empty"}}),
            "endpoint offset delta must be -1 or 1",
        ),
        (
            None,
            json!({"op":"if","condition":{"op":"kindIs","input":"third","kind":"int"},"then":valid,"else":valid}),
            "third input requires ternary control",
        ),
        (
            None,
            json!({"op":"bounds","lower":{"op":"input","input":"third","endpoint":"upper"},"upper":{"op":"empty"}}),
            "third input requires ternary control",
        ),
    ] {
        let error = unification::generate_with_policy(&control(function, result), "bad policy")
            .expect_err("invalid control");
        assert!(matches!(error, unification::Error::Program { .. }));
        assert_eq!(
            error.to_string(),
            format!("invalid unification control: {reason}")
        );
    }
    // Serialization tags are internal only, in both value and endpoint positions.
    for result in [
        json!({"op":"inputValue","input":"left"}),
        json!({"op":"integerValue","value":3}),
        json!({"op":"unaryFail","reason":"logical"}),
        json!({"op":"bounds","lower":{"op":"inputEndpoint","input":"left","endpoint":"lower"},"upper":{"op":"empty"}}),
        json!({"op":"bounds","lower":{"op":"integerEndpoint","value":3},"upper":{"op":"empty"}}),
        json!({"op":"bounds","lower":{"op":"listCountEndpoint"},"upper":{"op":"empty"}}),
    ] {
        assert!(matches!(
            unification::generate_with_policy(&control(None, result), "bad policy"),
            Err(unification::Error::Json { .. })
        ));
    }
    for input in [
        r#"{"formatVersion":1,"formatVersion":1,"result":{"op":"integer","value":1}}"#,
        r#"{"formatVersion":1,"result":{"op":"input","input":"left","input":"right"}}"#,
        r#"{"formatVersion":1,"result":{"op":"bounds","lower":{"op":"integer","value":1,"value":2},"upper":{"op":"empty"}}}"#,
    ] {
        let error =
            unification::generate_with_policy(input, "bad policy").expect_err("original duplicate");
        assert!(matches!(error, unification::Error::Json { .. }));
        assert!(error.to_string().contains("duplicate field"));
    }
}
#[test]
fn exact_control_structure_bounds_and_recovery() -> TestResult {
    let ignore = policy(json!({"program":{"op":"text","value":"validated"}}));
    // Root/result/lower begin at levels 1/2/3; leaf scalar is 4+n.
    for (offsets, succeeds) in [(60, true), (61, false)] {
        let mut endpoint = json!({"op":"integer","value":0});
        for _ in 0..offsets {
            endpoint = json!({"op":"offset","value":endpoint,"delta":1});
        }
        let input = control(
            None,
            json!({"op":"bounds","lower":endpoint,"upper":{"op":"empty"}}),
        );
        let answer = unification::generate_with_policy(&input, &ignore);
        if succeeds {
            assert_eq!(answer?, "validated");
        } else {
            assert_eq!(
                answer.expect_err("level 65").to_string(),
                "invalid unification control: exceeds 64 JSON levels or 512 JSON nodes"
            );
        }
    }
    // Five base nodes, 57 nine-node wrappers, two conditions shortened by three.
    let mut result = json!({"op":"integer","value":0});
    for index in 0..57 {
        let condition = if index < 2 {
            json!({"op":"same"})
        } else {
            json!({"op":"kindIs","input":"left","kind":"int"})
        };
        result = json!({"op":"if","condition":condition,"then":result,"else":{"op":"integer","value":1}});
    }
    let input = control(None, result);
    assert_eq!(
        unification::generate_with_policy(&input, &ignore)?,
        "validated"
    );
    let mut oversized: Value = serde_json::from_str(&input)?;
    oversized["extra"] = json!(0); // 513th node; guard precedes unknown-field decoding.
    assert_eq!(
        unification::generate_with_policy(&oversized.to_string(), &ignore)
            .expect_err("node 513")
            .to_string(),
        "invalid unification control: exceeds 64 JSON levels or 512 JSON nodes"
    );
    assert_eq!(
        unification::generate_with_policy(&input, &ignore)?,
        "validated"
    );
    Ok(())
}
#[test]
fn real_cli_isolated_failures_and_success() -> TestResult {
    use std::os::unix::fs::PermissionsExt;
    let executable = Path::new(CLI);
    assert!(executable.is_absolute());
    fs::File::open(executable)?;
    assert_ne!(fs::metadata(executable)?.permissions().mode() & 0o111, 0);
    let root = std::env::temp_dir().join(format!("native-unifier-cli-{}", std::process::id()));
    fs::create_dir(&root)?;
    let home = root.join("home");
    fs::create_dir(&home)?;
    let good = root.join("good.json");
    let typed = root.join("typed.json");
    let custom = root.join("custom.json");
    let missing = root.join("missing.json");
    fs::write(&good, control(None, json!({"op":"boolean","value":false})))?;
    fs::write(&typed, control(None, json!({"op":"input","input":"third"})))?;
    fs::write(
        &custom,
        policy(json!({"program":{"op":"get","name":"missing"}})),
    )?;
    let run = |args: &[&Path]| {
        Command::new(executable)
            .args(args)
            .env_clear()
            .env("HOME", &home)
            .env("PATH", "/nonexistent")
            .current_dir(&root)
            .output()
    };
    for (args, diagnostic, prefix) in [
        (
            vec![],
            "usage: bootstrap-unify-codegen <control.json> [lowering.json]".to_owned(),
            false,
        ),
        (
            vec![good.as_path(), custom.as_path(), typed.as_path()],
            "usage: bootstrap-unify-codegen <control.json> [lowering.json]".to_owned(),
            false,
        ),
        (
            vec![missing.as_path()],
            format!("cannot read {}: ", missing.display()),
            true,
        ),
        (
            vec![good.as_path(), missing.as_path()],
            format!("cannot read {}: ", missing.display()),
            true,
        ),
        (
            vec![typed.as_path()],
            "invalid unification control: third input requires ternary control".to_owned(),
            false,
        ),
        (
            vec![good.as_path(), custom.as_path()],
            "lowering: unknown binding".to_owned(),
            false,
        ),
    ] {
        let output = run(&args)?;
        assert_eq!(output.status.code(), Some(2));
        assert!(output.stdout.is_empty());
        let stderr = String::from_utf8(output.stderr)?;
        if prefix {
            assert!(stderr.starts_with(&diagnostic), "{stderr}");
        } else {
            assert_eq!(stderr, format!("{diagnostic}\n"));
        }
    }
    let output = run(&[&good])?;
    assert!(output.status.success());
    assert!(output.stderr.is_empty());
    assert_eq!(
        String::from_utf8(output.stdout)?,
        source(
            "unify",
            "_left: Value, _right: Value",
            "Ok::<_, Error>(Value::Boolean(false))"
        )
    );
    fs::write(
        &custom,
        policy(json!({"program":{"op":"text","value":"custom success\n"}})),
    )?;
    let output = run(&[&good, &custom])?;
    assert!(output.status.success());
    assert!(output.stderr.is_empty());
    assert_eq!(output.stdout, b"custom success\n");
    fs::remove_dir_all(root)?;
    Ok(())
}
#[test]
fn rendering_and_meta_compilation_quote_data() -> TestResult {
    let quotes = policy(json!({"quoted":{"op":"string","field":"value"}}));
    let driver = lowering::Policy::parse(&quotes)?;
    assert_eq!(
        lowering::Context::run(&json!({"op":"quoted","value":"\"\\\n雪"}), &driver)?,
        "\"\\\"\\\\\\n雪\""
    );
    let generated = lowering::generate(&quotes)?;
    let expected = r#"// Generated lowering driver. Do not edit.
use bootstrap_executor::lowering::{self, Context, Driver, Error};
use serde_json::Value;

pub struct Compiled;

impl Driver for Compiled {
    fn render(&self, ctx: &mut Context, _node: &Value, _depth: usize) -> Result<String, Error> {
        match lowering::instruction_op(_node)? {
            "quoted" => ctx.string(_node, "value"),
            op => Err(lowering::missing_case(op)),
        }
    }
}

pub fn lower(node: &Value) -> Result<String, Error> {
    Context::run(node, &Compiled)
}
"#;
    assert_eq!(generated, expected);
    Ok(())
}
#[cfg(feature = "compiled-lowering")]
#[test]
fn both_fresh_compiled_drivers_execute_through_context() -> TestResult {
    use bootstrap_executor::{compiled_meta_lowering, compiled_unify_lowering};
    let unify = json!({"op":"program","function":"logicalNot","unary":true,"ternary":false,"result":{"op":"unaryFail","reason":"logical"}});
    assert_eq!(
        lowering::Context::run(&unify, &compiled_unify_lowering::Compiled)?,
        source("logical_not", "_left: Value", "Err(Error::Logical)")
    );
    let meta = json!({"op":"selectCase","tag":"\"\\\n雪","value":{"op":"text","value":"line\n"}});
    assert_eq!(
        lowering::Context::run(&meta, &compiled_meta_lowering::Compiled)?,
        "\"\\\"\\\\\\n雪\" => ctx.text(\"line\\n\"), "
    );
    assert!(
        lowering::Context::run(
            &json!({"op":"unaryFail","reason":"unknown"}),
            &compiled_unify_lowering::Compiled
        )
        .is_err()
    );
    assert!(
        lowering::Context::run(
            &json!({"op":"selectCase","tag":4}),
            &compiled_meta_lowering::Compiled
        )
        .is_err()
    );
    assert_eq!(
        lowering::Context::run(
            &json!({"op":"text","value":"ok"}),
            &compiled_meta_lowering::Compiled
        )?,
        "ctx.text(\"ok\")"
    );
    Ok(())
}
