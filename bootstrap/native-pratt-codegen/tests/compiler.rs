#[test]
fn complete_nested_return_layout_without_runtime_simulation() -> TestResult {
    let input = control(
        "parser",
        r#"[{"op":"if","condition":{"op":"boolean","value":false},"then":[{"op":"return"}]},{"op":"while","condition":{"op":"and","left":{"op":"boolean","value":false},"right":{"op":"atLeast","left":{"op":"precedence"},"right":{"op":"minimum"}}},"body":[{"op":"return"}]},{"op":"if","condition":{"op":"boolean","value":true},"then":[{"op":"if","condition":{"op":"boolean","value":false},"then":[{"op":"return"}],"else":[{"op":"return"}]}],"else":[{"op":"return"}]}]"#,
    );
    let expected = source(
        "parser::{Error, Frame}",
        "Frame<'_, '_>",
        "_frame.step()?;\nif false {\n_frame.step()?;\nreturn Ok(());\n}\nwhile { _frame.step()?; false && _frame.precedence()? >= _frame.minimum() } {\n_frame.step()?;\nreturn Ok(());\n}\n_frame.step()?;\nif true {\n_frame.step()?;\nif false {\n_frame.step()?;\nOk(())\n} else {\n_frame.step()?;\nOk(())\n}\n} else {\n_frame.step()?;\nOk(())\n}\n",
    );
    assert_eq!(pratt::generate(&input)?, expected);
    assert_eq!(pratt::generate_with_policy(&input, POLICY)?, expected);
    Ok(())
}
#[test]
fn trusted_custom_policy_observes_actual_private_metadata_and_recovers() -> TestResult {
    let observer = r#"{"formatVersion":1,"cases":{"program":{"op":"concat","parts":[{"op":"string","field":"target"},{"op":"string","field":"tail"},{"op":"list","field":"body"}]},"action":{"op":"string","field":"action"},"selectorAction":{"op":"string","field":"action"},"return":{"op":"string","field":"position"},"if":{"op":"concat","parts":[{"op":"lower","field":"condition"},{"op":"list","field":"then"},{"op":"list","field":"else"}]},"itemKindIs":{"op":"string","field":"kind"},"sliceKindIs":{"op":"string","field":"kind"}}}"#;
    let input = control("parser", r#"[{"op":"primary"},{"op":"scanSelector"}]"#);
    assert_eq!(
        pratt::generate_with_policy(&input, observer)?,
        "\"parser\"\"value\"\"primary\"\"scanSelector\""
    );
    for (target, kind_op, kind) in [
        ("list", "itemKindIs", "bounds"),
        ("record", "itemKindIs", "text"),
        ("conjunction", "itemKindIs", "top"),
        ("slice", "sliceKindIs", "list"),
    ] {
        let body = format!(
            r#"[{{"op":"if","condition":{{"op":"{kind_op}","kind":"{kind}"}},"then":[{{"op":"return"}}],"else":[{{"op":"return"}}]}}]"#
        );
        assert_eq!(
            pratt::generate_with_policy(&control(target, &body), observer)?,
            format!("\"{target}\"\"return\"\"{kind}\"\"tail\"\"tail\"")
        );
    }
    for invalid_policy in [
        "not JSON",
        r#"{"formatVersion":1,"cases":{"program":{"op":"get","name":"missing"}}}"#,
    ] {
        assert!(matches!(
            pratt::generate_with_policy(&input, invalid_policy),
            Err(pratt::Error::Lowering { .. })
        ));
        assert_eq!(
            pratt::generate_with_policy(&input, observer)?,
            "\"parser\"\"value\"\"primary\"\"scanSelector\""
        );
    }
    let changed =
        r#"{"formatVersion":1,"cases":{"program":{"op":"text","value":"// trusted override\n"}}}"#;
    assert_eq!(
        pratt::generate_with_policy(&input, changed)?,
        "// trusted override\n"
    );
    assert_ne!(pratt::generate(&input)?, "// trusted override\n");
    Ok(())
}
#[test]
fn typed_family_and_reachability_errors_precede_invalid_or_ignoring_policy() {
    let ignore = r#"{"formatVersion":1,"cases":{"program":{"op":"text","value":"ignored"}}}"#;
    for (target, body, reason) in [
        (
            "list",
            r#"[{"op":"if","condition":{"op":"boolean","value":false},"then":[{"op":"primary"}]}]"#,
            "operation does not match control target",
        ),
        (
            "parser",
            r#"[{"op":"while","condition":{"op":"and","left":{"op":"boolean","value":false},"right":{"op":"hasItem"}},"body":[]}]"#,
            "operation does not match control target",
        ),
        (
            "slice",
            r#"[{"op":"if","condition":{"op":"boolean","value":true},"then":[],"else":[{"op":"appendItem"}]}]"#,
            "operation does not match control target",
        ),
        (
            "record",
            r#"[{"op":"seedTop"}]"#,
            "operation does not match control target",
        ),
        (
            "conjunction",
            r#"[{"op":"finishList"}]"#,
            "operation does not match control target",
        ),
        (
            "list",
            r#"[{"op":"if","condition":{"op":"and","left":{"op":"hasItem"},"right":{"op":"hasLower"}},"then":[]}]"#,
            "operation does not match control target",
        ),
        (
            "parser",
            r#"[{"op":"return"},{"op":"primary"}]"#,
            "statements after definite return",
        ),
        (
            "parser",
            r#"[{"op":"while","condition":{"op":"boolean","value":false},"body":[{"op":"return"},{"op":"primary"}]}]"#,
            "statements after definite return",
        ),
        (
            "parser",
            r#"[{"op":"if","condition":{"op":"boolean","value":false},"then":[{"op":"return"},{"op":"primary"}]}]"#,
            "statements after definite return",
        ),
        (
            "parser",
            r#"[{"op":"if","condition":{"op":"boolean","value":true},"then":[{"op":"return"}],"else":[{"op":"return"}]},{"op":"primary"}]"#,
            "statements after definite return",
        ),
    ] {
        for policy in ["bad policy", ignore] {
            let error = pratt::generate_with_policy(&control(target, body), policy)
                .expect_err("complete typed validation");
            assert!(matches!(error, pratt::Error::Program { .. }));
            assert_eq!(
                error.to_string(),
                format!("invalid Pratt control: {reason}")
            );
        }
    }
    assert_eq!(
        pratt::generate_with_policy(&control("parser", "[]"), ignore).expect("recovery"),
        "ignored"
    );
}
#[test]
fn original_wire_rejects_duplicates_internal_facts_and_numeric_overflow() {
    for input in [
        r#"{"formatVersion":1,"formatVersion":1,"body":[]}"#,
        r#"{"formatVersion":1,"body":[{"op":"primary","op":"return"}]}"#,
        r#"{"formatVersion":1,"body":[{"op":"parseGroup","minimum":{"op":"integer","value":0,"value":1}}]}"#,
    ] {
        let error = pratt::generate_with_policy(input, "bad policy").expect_err("duplicate");
        assert!(matches!(error, pratt::Error::Json { .. }));
        assert!(error.to_string().contains("duplicate field"));
    }
    for body in [
        r#"[{"op":"action","action":"primary"}]"#,
        r#"[{"op":"selectorAction","action":"scanSelector"}]"#,
        r#"[{"op":"parseMinimum","minimum":{"op":"integer","value":0}}]"#,
        r#"[{"op":"return","position":"tail"}]"#,
        r#"[{"op":"primary","action":"primary"}]"#,
        r#"[{"op":"parseGroup","minimum":{"op":"integer","value":256}}]"#,
        r#"[{"op":"parseGroup","minimum":{"op":"integer","value":-1}}]"#,
    ] {
        assert!(
            matches!(
                pratt::generate_with_policy(&control("parser", body), "bad policy"),
                Err(pratt::Error::Json { .. })
            ),
            "{body}"
        );
    }
    for input in [
        r#"{"formatVersion":1,"target":"List","body":[]}"#,
        r#"{"formatVersion":1,"target":0,"body":[]}"#,
        r#"{"formatVersion":1,"body":[],"tail":"return"}"#,
        r#"{"formatVersion":1,"target":"slice","body":[{"op":"defaultSliceLower","value":9223372036854775808}]}"#,
        r#"{"formatVersion":1,"target":"slice","body":[{"op":"defaultSliceLower","value":-9223372036854775809}]}"#,
    ] {
        assert!(
            matches!(
                pratt::generate_with_policy(input, "bad policy"),
                Err(pratt::Error::Json { .. })
            ),
            "{input}"
        );
    }
}
#[test]
fn quoted_data_and_complete_meta_driver_source() -> TestResult {
    let policy = r#"{"formatVersion":1,"cases":{"quoted":{"op":"string","field":"value"}}}"#;
    let driver = lowering::Policy::parse(policy)?;
    assert_eq!(
        lowering::Context::run(&json!({"op":"quoted","value":"\"\\\n雪"}), &driver)?,
        "\"\\\"\\\\\\n雪\""
    );
    let expected = "// Generated lowering driver. Do not edit.\nuse bootstrap_executor::lowering::{self, Context, Driver, Error};\nuse serde_json::Value;\n\npub struct Compiled;\n\nimpl Driver for Compiled {\n    fn render(&self, ctx: &mut Context, _node: &Value, _depth: usize) -> Result<String, Error> {\n        match lowering::instruction_op(_node)? {\n            \"quoted\" => ctx.string(_node, \"value\"),\n            op => Err(lowering::missing_case(op)),\n        }\n    }\n}\n\npub fn lower(node: &Value) -> Result<String, Error> {\n    Context::run(node, &Compiled)\n}\n";
    assert_eq!(lowering::generate(policy)?, expected);
    Ok(())
}
#[test]
fn real_cargo_cli_cleared_environment_negatives_then_success() -> TestResult {
    use std::os::unix::fs::PermissionsExt;
    let executable = Path::new(CLI);
    assert!(executable.is_absolute());
    let metadata = fs::metadata(executable)?;
    assert!(metadata.is_file());
    fs::File::open(executable)?;
    assert_ne!(metadata.permissions().mode() & 0o111, 0);
    let root = std::env::temp_dir().join(format!("native-pratt-cli-{}", std::process::id()));
    fs::create_dir(&root)?;
    let home = root.join("home");
    fs::create_dir(&home)?;
    let good = root.join("good.json");
    let typed = root.join("typed.json");
    let custom = root.join("custom.json");
    let missing = root.join("missing.json");
    fs::write(&good, control("parser", r#"[{"op":"primary"}]"#))?;
    fs::write(&typed, control("list", r#"[{"op":"primary"}]"#))?;
    fs::write(
        &custom,
        r#"{"formatVersion":1,"cases":{"program":{"op":"get","name":"missing"}}}"#,
    )?;
    let run = |args: &[&Path]| {
        Command::new(executable)
            .args(args)
            .env_clear()
            .env("HOME", &home)
            .env("PATH", "/nonexistent")
            .current_dir(&root)
            .output()
    };
    for (args, diagnostic, read_prefix) in [
        (
            vec![],
            "usage: bootstrap-pratt-codegen <control.json> [lowering.json]".to_owned(),
            false,
        ),
        (
            vec![good.as_path(), custom.as_path(), typed.as_path()],
            "usage: bootstrap-pratt-codegen <control.json> [lowering.json]".to_owned(),
            false,
        ),
        (
            vec![missing.as_path()],
            format!("cannot read {}: ", missing.display()),
            true,
        ),
        (
            vec![good.as_path(), missing.as_path()],
            format!("cannot read {}: ", missing.display()),
            true,
        ),
        (
            vec![typed.as_path()],
            "invalid Pratt control: operation does not match control target".to_owned(),
            false,
        ),
        (
            vec![typed.as_path(), custom.as_path()],
            "invalid Pratt control: operation does not match control target".to_owned(),
            false,
        ),
        (
            vec![good.as_path(), custom.as_path()],
            "lowering: unknown binding".to_owned(),
            false,
        ),
    ] {
        let output = run(&args)?;
        assert_eq!(output.status.code(), Some(2));
        assert!(output.stdout.is_empty());
        let stderr = String::from_utf8(output.stderr)?;
        if read_prefix {
            assert!(stderr.starts_with(&diagnostic), "{stderr}");
            assert!(stderr.len() > diagnostic.len() + 1);
        } else {
            assert_eq!(stderr, format!("{diagnostic}\n"));
        }
    }
    let output = run(&[&good])?;
    assert!(output.status.success());
    assert!(output.stderr.is_empty());
    assert_eq!(
        String::from_utf8(output.stdout)?,
        source(
            "parser::{Error, Frame}",
            "Frame<'_, '_>",
            "_frame.step()?;\n_frame.primary()?;\nOk(())\n"
        )
    );
    fs::write(
        &custom,
        r#"{"formatVersion":1,"cases":{"program":{"op":"text","value":"custom success\n"}}}"#,
    )?;
    let output = run(&[&good, &custom])?;
    assert!(output.status.success());
    assert!(output.stderr.is_empty());
    assert_eq!(output.stdout, b"custom success\n");
    fs::remove_dir_all(root)?;
    Ok(())
}
#[cfg(feature = "compiled-lowering")]
#[test]
fn each_fresh_compiled_driver_has_independent_context_success_error_success() -> TestResult {
    use bootstrap_executor::{compiled_meta_lowering, compiled_pratt_lowering};
    let pratt = json!({"op":"program","target":"record","tail":"return","body":[{"op":"action","action":"finishRecord"},{"op":"return","position":"tail"}]});
    let expected = source(
        "{Error, runtime::RecordFrame}",
        "RecordFrame<'_>",
        "_frame.step()?;\n_frame.finish_record()?;\n_frame.step()?;\nOk(())\n",
    );
    assert_eq!(
        lowering::Context::run(&pratt, &compiled_pratt_lowering::Compiled)?,
        expected
    );
    assert!(
        lowering::Context::run(
            &json!({"op":"program","target":"notATarget","tail":"value","body":[]}),
            &compiled_pratt_lowering::Compiled
        )
        .is_err()
    );
    assert_eq!(
        lowering::Context::run(&pratt, &compiled_pratt_lowering::Compiled)?,
        expected
    );
    let meta = json!({"op":"selectCase","tag":"\"\\\n雪","value":{"op":"text","value":"line\n"}});
    let expected_meta = "\"\\\"\\\\\\n雪\" => ctx.text(\"line\\n\"), ";
    assert_eq!(
        lowering::Context::run(&meta, &compiled_meta_lowering::Compiled)?,
        expected_meta
    );
    assert!(
        lowering::Context::run(
            &json!({"op":"selectCase","tag":4}),
            &compiled_meta_lowering::Compiled
        )
        .is_err()
    );
    assert_eq!(
        lowering::Context::run(&meta, &compiled_meta_lowering::Compiled)?,
        expected_meta
    );
    Ok(())
}
