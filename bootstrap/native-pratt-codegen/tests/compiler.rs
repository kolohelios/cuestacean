//! Independent source predictions, not execution of the emitted frame wrappers.
use bootstrap_executor::{lowering, pratt};
use serde_json::json;
use std::{fs, path::Path, process::Command};

type TestResult = Result<(), Box<dyn std::error::Error>>;
const CLI: &str = env!("CARGO_BIN_EXE_bootstrap-pratt-codegen");
const POLICY: &str = include_str!(concat!(
    env!("CUESTACEAN_BOOTSTRAP_JSON"),
    "/pratt-lowering.json"
));
fn control(target: &str, body: &str) -> String {
    format!(r#"{{"formatVersion":1,"target":"{target}","body":{body}}}"#)
}
fn source(import: &str, frame: &str, body: &str) -> String {
    format!(
        "// Generated by bootstrap-pratt-codegen. Do not edit by hand.\nuse crate::{import};\npub fn execute(_frame: &mut {frame}) -> Result<(), Error> {{\n{body}}}\n"
    )
}
