//! Same-source compiler boundary evidence, not a native constructor closure.
#[cfg(feature = "compiled-lowering")]
pub use bootstrap_executor::compiled_unify_lowering;
pub use bootstrap_executor::lowering;
#[path = "../src/unification/compiler.rs"]
mod compiler;

fn control(function: &str, result: &str) -> String {
    format!(r#"{{"formatVersion":1,{function}"result":{result}}}"#)
}

struct Metadata(serde_json::Value);
impl lowering::Driver for Metadata {
    fn render(
        &self,
        _: &mut lowering::Context,
        node: &serde_json::Value,
        _: usize,
    ) -> Result<String, lowering::Error> {
        assert_eq!(node, &self.0);
        Ok("checked".to_owned())
    }
}

#[test]
fn complete_metadata_and_serialization_only_projection() {
    for (function, result, expected) in [
        (
            "",
            r#"{"op":"input","input":"right"}"#,
            r#"{"op":"program","function":"unify","unary":false,"ternary":false,"result":{"op":"inputValue","input":"right"}}"#,
        ),
        (
            r#""function":"logicalNot","#,
            r#"{"op":"input","input":"left"}"#,
            r#"{"op":"program","function":"logicalNot","unary":true,"ternary":false,"result":{"op":"inputValue","input":"left"}}"#,
        ),
        (
            r#""function":"logicalNot","#,
            r#"{"op":"fail","reason":"logical"}"#,
            r#"{"op":"program","function":"logicalNot","unary":true,"ternary":false,"result":{"op":"unaryFail","reason":"logical"}}"#,
        ),
        (
            r#""function":"listSlice","#,
            r#"{"op":"input","input":"third"}"#,
            r#"{"op":"program","function":"listSlice","unary":false,"ternary":true,"result":{"op":"inputValue","input":"third"}}"#,
        ),
    ] {
        let program = compiler::parse(&control(function, result)).expect("valid control");
        let driver = Metadata(serde_json::from_str(expected).expect("handwritten metadata"));
        assert_eq!(
            compiler::lower(program, &driver).expect("real context"),
            "checked"
        );
    }
}

#[test]
fn typed_rejections_precede_invalid_policy() {
    for (function, result, json_error) in [
        (
            r#""function":"logicalNot","#,
            r#"{"op":"input","input":"right"}"#,
            false,
        ),
        (
            "",
            r#"{"op":"if","condition":{"op":"kindIs","input":"left","kind":"null"},"then":{"op":"input","input":"left"},"else":{"op":"input","input":"third"}}"#,
            false,
        ),
        (
            "",
            r#"{"op":"letBounds","lower":{"op":"local","endpoint":"lower"},"upper":{"op":"empty"},"result":{"op":"input","input":"left"}}"#,
            false,
        ),
        ("", r#"{"op":"input","input":"left","input":"right"}"#, true),
        ("", r#"{"op":"inputValue","input":"left"}"#, true),
        ("", r#"{"op":"integerValue","value":1}"#, true),
        (
            r#""function":"logicalNot","#,
            r#"{"op":"unaryFail","reason":"logical"}"#,
            true,
        ),
        (
            "",
            r#"{"op":"bounds","lower":{"op":"inputEndpoint","input":"left","endpoint":"lower"},"upper":{"op":"empty"}}"#,
            true,
        ),
        (
            "",
            r#"{"op":"bounds","lower":{"op":"integerEndpoint","value":1},"upper":{"op":"empty"}}"#,
            true,
        ),
        (
            "",
            r#"{"op":"bounds","lower":{"op":"listCountEndpoint"},"upper":{"op":"empty"}}"#,
            true,
        ),
    ] {
        let error = compiler::generate_with_policy(&control(function, result), "not JSON")
            .expect_err("control must reject before policy decoding");
        if json_error {
            assert!(matches!(error, compiler::Error::Json { .. }));
        } else {
            assert!(matches!(error, compiler::Error::Program { .. }));
        }
    }
}

#[test]
fn real_default_and_reference_generation() {
    let input = control("", r#"{"op":"input","input":"left"}"#);
    let expected = "// Generated by bootstrap-unify-codegen. Do not edit by hand.\nuse crate::{Error, runtime::Value};\npub fn unify(_left: Value, _right: Value) -> Result<Value, Error> {\nOk::<_, Error>(_left.clone())\n}\n";
    let policy = include_str!(concat!(
        env!("CUESTACEAN_BOOTSTRAP_JSON"),
        "/unify-lowering.json"
    ));
    assert_eq!(
        compiler::generate(&input).expect("default backend"),
        expected
    );
    assert_eq!(
        compiler::generate_with_policy(&input, policy).expect("reference backend"),
        expected
    );
}

#[test]
fn custom_policy_observes_arity_and_recovers_after_failure() {
    let policy = r#"{"formatVersion":1,"cases":{"program":{"op":"concat","parts":[{"op":"boolean","field":"unary"},{"op":"text","value":"/"},{"op":"boolean","field":"ternary"}]}}}"#;
    let input = r#"{"op":"input","input":"left"}"#;
    let valid = control("", input);
    assert!(matches!(
        compiler::generate_with_policy(&valid, "not JSON"),
        Err(compiler::Error::Lowering { .. })
    ));
    for (function, expected) in [
        (r#""function":"logicalNot","#, "true/false"),
        ("", "false/false"),
        (r#""function":"listSlice","#, "false/true"),
    ] {
        assert_eq!(
            compiler::generate_with_policy(&control(function, input), policy)
                .expect("custom metadata policy"),
            expected
        );
    }
}
