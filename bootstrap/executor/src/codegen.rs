use serde_json::to_value;
use snafu::ResultExt;

use crate::{
    Error, JsonSnafu, Rules,
    lowering::{Context, Driver, Policy},
    parse_rules,
};

/// Lower rules using the CUE-owned instruction-expression program.
/// Fresh compiler seeds consume upstream-built JSON, never committed Rust.
pub fn generate(input: &str) -> Result<String, Error> {
    #[cfg(feature = "compiled-lowering")]
    {
        emit(parse_rules(input)?, &crate::compiled_lowering::Compiled)
    }
    #[cfg(not(feature = "compiled-lowering"))]
    {
        generate_with_policy(
            input,
            include_str!(concat!(env!("CUESTACEAN_BOOTSTRAP_JSON"), "/lowering.json")),
        )
    }
}

/// Override the trusted lowering policy, not the input instruction language.
pub fn generate_with_policy(input: &str, policy: &str) -> Result<String, Error> {
    let rules = parse_rules(input)?;
    let policy = Policy::parse(policy).map_err(|source| Error::Lowering { source })?;
    emit(rules, &policy)
}

fn emit(rules: Rules, driver: &dyn Driver) -> Result<String, Error> {
    let mut source = String::from(
        "// Generated by bootstrap-codegen. Do not edit by hand.\n\
         use bootstrap_executor::{Error, runtime};\n\
         use serde_json::Value;\n\n\
         pub fn execute(input: &str) -> Result<i64, Error> {\n\
             runtime::concrete(evaluate(&runtime::program(input)?)?)\n\
         }\n\n\
         pub fn execute_json(input: &str) -> Result<Value, Error> {\n\
             runtime::concrete_json(evaluate(&runtime::program(input)?)?)\n\
         }\n\n\
         fn evaluate(node: &Value) -> Result<runtime::Value, Error> {\n\
             match runtime::kind(node)? {\n",
    );
    // Outer module assembly remains native; per-instruction recursion is CUE-owned.
    for (kind, rule) in rules.rules {
        let instruction = to_value(&rule.result).context(JsonSnafu { document: "rules" })?;
        let expression =
            Context::run(&instruction, driver).map_err(|source| Error::Lowering { source })?;
        source.push_str(&format!("{kind:?} => {expression},\n"));
    }
    source.push_str(
        "kind => Err(Error::MissingRule { kind: kind.to_string() }),\n\
             }\n\
         }\n",
    );
    Ok(source)
}
