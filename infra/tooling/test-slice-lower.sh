#!/usr/bin/env bash
# Focused #296 proof. Construction/closure and runtime tests belong to Nix.
set -euo pipefail
[[ $# = 10 ]] || { echo 'expected CUE JQ SPEC_EXPORTER PRATT_CODEGEN RUSTFMT NATIVE_JSON EXPORTS_DIR BOOTSTRAP_SOURCE_ROOT PROVIDER_SCRIPT OUT' >&2; exit 1; }
CUE=$1 JQ=$2 SPEC_EXPORTER=$3 PRATT_CODEGEN=$4 RUSTFMT=$5
NATIVE_JSON=$6 EXPORTS_DIR=$7 SOURCE=$8 PROVIDER_SCRIPT=$9 OUT=${10}
for tool in "$CUE" "$JQ" "$SPEC_EXPORTER" "$PRATT_CODEGEN" "$RUSTFMT"; do
  [[ $tool = /* && -f $tool && -r $tool && -x $tool ]]
done
for path in "$NATIVE_JSON" "$EXPORTS_DIR" "$SOURCE" "$PROVIDER_SCRIPT" "$OUT"; do
  [[ $path = /* ]]
done
mkdir -p "$OUT/work/home" "$OUT/receipts"
cd "$OUT/work"
HOME_DIR=$PWD/home
TRACE=$OUT/receipts/cue-argv
TRACE_ALL=$OUT/receipts/all-cue-argv
: > "$TRACE"
: > "$TRACE_ALL"
cue() {
  local invocation
  printf -v invocation '%q ' "$@"
  printf '%s\n' "$invocation" >> "$TRACE"
  printf '%s\n' "$invocation" >> "$TRACE_ALL"
  env -i HOME="$HOME_DIR" PATH=/nonexistent "$CUE" "$@"
}
jq() { env -i HOME="$HOME_DIR" PATH=/nonexistent "$JQ" "$@"; }
# This is the SAME gate/route sourced by production, not a verifier substitute.
source "$PROVIDER_SCRIPT"
declare -F slice_lower_provider > /dev/null
cue version > "$OUT/receipts/cue-version"
grep -Ex 'CUE language version v0\.16\.1' "$OUT/receipts/cue-version"
schema=$SOURCE/schema.cue
fragment=$SOURCE/slice-control-fragments.cue
owner=$SOURCE/slice-lower-default.cue
root=$SOURCE/slice-lower-default-root.cue
canonical=$SOURCE/slice-control.cue
one=$SOURCE/tests/valid/slice-control-lower-one.cue
tail=$SOURCE/tests/valid/slice-control-tail.cue
for path in "$schema" "$fragment" "$owner" "$root" "$canonical" "$one" "$tail"; do
  test -f "$path" && test -r "$path"
done

# Exact inverse hash from immutable 4635280979cff023325bcf1b639c0568bbba8bd3.
# Bash substitution is counted and the entire recovered file is hash checked.
IFS= read -r -d '' text < "$fragment" || [[ -n $text ]]
needle='_lowerDefault: #SliceLowerInput.v'
[[ $text = *"$needle"* ]]
rest=${text#*"$needle"}
[[ $rest != *"$needle"* ]]
printf '%s' "${text/"$needle"/'_lowerDefault: *0 | 1'}" > original.cue
printf '%s  %s\n' dbff081af2396ad20d10ab49fb073a80b956b8829d16ef27af5666f6421900d6 original.cue > inverse.sha256
sha256sum -c inverse.sha256 > "$OUT/receipts/inverse-check"
# No schema/selector/golden drift can hide in the enumerated proof source cut.
while read -r hash relative; do
  printf '%s  %s\n' "$hash" "$SOURCE/$relative"
done > unchanged.sha256 <<'HASHES'
f2f414bd2b4a8ceee39365c10ea7254dcc51ca6a2d2f3745edec1d0de66b2b9e schema.cue
4715e2d4115b6f3037025dae28fc63799460c57d9f260a3c157a552c490671aa slice-control.cue
9637e991e0a4014c976f5cb8731c4421c21025a43480ebeb52402da200c33174 tests/valid/slice-control-lower-one.cue
c4f513e95ae7bf994c863094c144962581f964a0207f60711340d4b233940cdc tests/valid/slice-control-tail.cue
d81d692c443d31b6389a13efdd57e152d0e0ca2511e8fe676db6f5a20f600ecd generated/slice-control.rs
8d79dd9800fb04bf23258c7d21163cd46542b8d28a9a5fbbab4112431b7eb710 generated/slice-control-lower-one.rs
018e6b2f4484ea62df172b135c6051fa2f87396a17ecb56e74ff5e9b7e68c90f generated/slice-control-tail.rs
HASHES
sha256sum -c unchanged.sha256 > "$OUT/receipts/unchanged-check"

# Independent whole PROGRAM expectations; no oracle/generated input supplies them.
for value in 0 1; do
  jq -n -S --argjson value "$value" '{formatVersion:1,target:"slice",body:[
    {op:"evaluateSliceOperand"},
    {op:"if",condition:{op:"hasLower"},then:[{op:"evaluateSliceLower"}],
      else:[{op:"defaultSliceLower",value:$value}]},
    {op:"if",condition:{op:"hasUpper"},then:[{op:"evaluateSliceUpper"}],else:[
      {op:"if",condition:{op:"sliceKindIs",kind:"list"},then:[{op:"defaultSliceUpper"}],
        else:[{op:"rejectSliceOperand"}]}]},
    {op:"finishSlice"}]}' > "expected-$value.json"
done
jq -S '.body += [{op:"return"}]' expected-0.json > expected-tail.json
jq -S -n --slurpfile l expected-1.json --slurpfile r expected-0.json \
  '{l:$l[0],r:$r[0]}' > expected-mixed.json
format() { env -i HOME="$HOME_DIR" PATH=/nonexistent "$RUSTFMT" --edition 2024; }
generate() {
  env -i HOME="$HOME_DIR" PATH=/nonexistent "$PRATT_CODEGEN" "$1" | format
}
# Independent full Rust template, also checks instruction/step order.
for variant in 0 1 tail; do
  value=$variant
  extra=''
  if [[ $variant = tail ]]; then value=0; extra='_frame.step()?;'; fi
  printf '%s\n' '// Generated by bootstrap-pratt-codegen. Do not edit by hand.' \
    'use crate::{Error, runtime::SliceFrame};' \
    "pub fn execute(_frame: &mut SliceFrame<'_>) -> Result<(), Error> {" \
    '_frame.step()?;' '_frame.evaluate_slice_operand()?;' '_frame.step()?;' \
    'if _frame.has_lower()? {' '_frame.step()?;' '_frame.evaluate_slice_lower()?;' \
    '} else {' '_frame.step()?;' "_frame.default_slice_lower($value)?;" '}' \
    '_frame.step()?;' 'if _frame.has_upper()? {' '_frame.step()?;' \
    '_frame.evaluate_slice_upper()?;' '} else {' '_frame.step()?;' \
    'if _frame.slice_kind_is(crate::unification::Kind::List)? {' \
    '_frame.step()?;' '_frame.default_slice_upper()?;' '} else {' \
    '_frame.step()?;' '_frame.reject_slice_operand()?;' '}' '}' \
    '_frame.step()?;' '_frame.finish_slice()?;' "$extra" 'Ok(())' '}' \
    | format > "expected-$variant.rs"
done

# Successful calls require status zero, clean stderr and whole normalized output.
clean_json() {
  local destination=$1
  shift
  "$@" > "$destination.raw" 2> "$destination.err"
  test ! -s "$destination.err"
  test -s "$destination.raw"
  jq -S . "$destination.raw" > "$destination"
}
native() {
  env -i HOME="$HOME_DIR" PATH=/nonexistent "$SPEC_EXPORTER" "$@"
}
for order in forward reverse; do
  files=("$owner" "$root")
  if [[ $order = reverse ]]; then files=("$root" "$owner"); fi
  clean_json "native-$order.json" native "${files[@]}"
  printf '{"v":0}\n' | jq -S . > expected-helper.json
  cmp expected-helper.json "native-$order.json"
  clean_json "oracle-$order.json" cue export "${files[@]}"
  cmp "native-$order.json" "oracle-$order.json"
done
jq -S . "$NATIVE_JSON" > native-published.json
cmp expected-helper.json native-published.json

# All routes invoke the actual shared provider BEFORE building composition argv.
# Explicit returns are essential when this function is called in an if/|| context.
compose() {
  local fixture=$1 data=$2 raw=$3 selector=$4 order=$5
  slice_provider=POISONED_PREVIOUS_SELECTION
  slice_lower_provider "$fixture" "$data" "$raw" || return
  touch composition-entered
  [[ -n $slice_provider && $slice_provider != POISONED_PREVIOUS_SELECTION ]] || return 1
  if [[ $fixture != slice-control ]]; then
    [[ $slice_provider = "$raw" ]] || return 1
  else
    [[ $slice_provider != "$raw" ]] || return 1
  fi
  printf '%s\t%s\t%s\n' "$fixture" "$order" "$slice_provider" >> "$OUT/receipts/routes"
  local inputs=("$schema" "$fragment" "$slice_provider" "$selector")
  if [[ $order = reverse ]]; then inputs=("$selector" "$slice_provider" "$fragment" "$schema"); fi
  cue export "${inputs[@]}"
}
# Unknown keys cannot inherit a previous canonical selection or validate bad data.
for fixture in unrelated slice-control-tail slice-control-lower-one tests/valid/slice-control-other; do
  slice_provider=POISONED_PREVIOUS_SELECTION
  slice_lower_provider "$fixture" /nonexistent/native.json /nonexistent/raw.cue
  [[ -z $slice_provider ]]
done

# Whole baseline/raw/selected matrix, deliberately including selected tail as a
# reference experiment (its production key MUST select raw), never as a fallback.
for case in canonical one tail; do
  case "$case" in
    canonical) selector=$canonical; fixture=slice-control; expected=0; baseline=slice-control ;;
    one) selector=$one; fixture=tests/valid/slice-control-lower-one; expected=1; baseline=slice-control-lower-one ;;
    tail) selector=$tail; fixture=tests/valid/slice-control-tail; expected=tail; baseline=slice-control-tail ;;
  esac
  for order in forward reverse; do
    inputs=("$schema" "$PWD/original.cue" "$selector")
    if [[ $order = reverse ]]; then inputs=("$selector" "$PWD/original.cue" "$schema"); fi
    clean_json "original-$case-$order.json" cue export "${inputs[@]}"
    cmp "expected-$expected.json" "original-$case-$order.json"
    # tail key deliberately requests raw even for the raw canonical reference.
    clean_json "raw-$case-$order.json" compose tests/valid/slice-control-tail "$NATIVE_JSON" "$owner" "$selector" "$order"
    cmp "expected-$expected.json" "raw-$case-$order.json"
    clean_json "production-$case-$order.json" compose "$fixture" "$NATIVE_JSON" "$owner" "$selector" "$order"
    cmp "expected-$expected.json" "production-$case-$order.json"
    for route in original raw production; do
      generate "$route-$case-$order.json" > "$route-$case-$order.rs"
      cmp "expected-$expected.rs" "$route-$case-$order.rs"
      cmp "$SOURCE/generated/$baseline.rs" "$route-$case-$order.rs"
    done
    if [[ $case != one ]]; then
      clean_json "selected-$case-$order.json" compose slice-control "$NATIVE_JSON" "$owner" "$selector" "$order"
      cmp "expected-$expected.json" "selected-$case-$order.json"
      generate "selected-$case-$order.json" > "selected-$case-$order.rs"
      cmp "expected-$expected.rs" "selected-$case-$order.rs"
    fi
  done
  jq -S . "$EXPORTS_DIR/${fixture}.json" > exported.json
  cmp "expected-$expected.json" exported.json
done

printf '%s\n' 'package bootstrap' '{l:(#SliceControl & {_lowerDefault:1}),r:#SliceControl}' > mixed.cue
printf '%s\n' 'package bootstrap' '#SliceControl & {_lowerDefault:(*1|0)}' > opposite.cue
# Keep eval success distinct from incomplete export and setup/ordinary conflict.
eval_success() {
  cue eval "$@" > eval.out 2> eval.err
  test -s eval.out && test ! -s eval.err
}
expect_failure() {
  local label=$1 diagnostic=$2 status=0
  shift 2
  "$@" > "$label.out" 2> "$label.err" || status=$?
  test "$status" -eq 1 && test ! -s "$label.out" && test -s "$label.err"
  grep -E "$diagnostic" "$label.err" > /dev/null
  printf '%s\t%s\t%s\n' "$label" "$status" "$diagnostic" >> "$OUT/receipts/categories"
}
for order in forward reverse; do
  inputs=("$schema" "$PWD/original.cue" "$PWD/mixed.cue")
  if [[ $order = reverse ]]; then inputs=("$PWD/mixed.cue" "$PWD/original.cue" "$schema"); fi
  clean_json "original-mixed-$order.json" cue export "${inputs[@]}"
  cmp expected-mixed.json "original-mixed-$order.json"
  clean_json "raw-mixed-$order.json" compose tests/valid/slice-control-tail "$NATIVE_JSON" "$owner" "$PWD/mixed.cue" "$order"
  cmp expected-mixed.json "raw-mixed-$order.json"
  for side in l r; do
    jq -S ".$side" "raw-mixed-$order.json" > child.json
    generate child.json > child.rs
    if [[ $side = l ]]; then cmp expected-1.rs child.rs; else cmp expected-0.rs child.rs; fi
  done
  for bridge in "$PWD/original.cue" "$fragment"; do
    providers=()
    if [[ $bridge = "$fragment" ]]; then providers=("$owner"); fi
    inputs=("$schema" "$bridge" "${providers[@]}" "$PWD/opposite.cue")
    if [[ $order = reverse ]]; then inputs=("$PWD/opposite.cue" "${providers[@]}" "$bridge" "$schema"); fi
    eval_success "${inputs[@]}"
    expect_failure "opposite-$(basename "$bridge")-$order" 'incomplete value|unresolved disjunction' cue export "${inputs[@]}"
    grep -F 'body.1.else.0.value' "opposite-$(basename "$bridge")-$order.err" > /dev/null
  done
  clean_json "frozen-opposite-$order.json" compose slice-control "$NATIVE_JSON" "$owner" "$PWD/opposite.cue" "$order"
  cmp expected-0.json "frozen-opposite-$order.json"
  expect_failure "frozen-one-$order" 'conflicting values|empty disjunction' \
    compose slice-control "$NATIVE_JSON" "$owner" "$one" "$order"
  inputs=("$schema" "$fragment" "$slice_provider" "$one")
  if [[ $order = reverse ]]; then inputs=("$one" "$slice_provider" "$fragment" "$schema"); fi
  expect_failure "frozen-one-eval-$order" 'conflicting values|empty disjunction' cue eval "${inputs[@]}"
done
expect_failure no-owner 'not found|undefined' cue export "$schema" "$fragment" "$canonical"

# A corrupted but present raw provider is incomplete in isolation, yet the REAL
# lower-one context can fill it without the gate. Demonstrate both facts first.
printf '%s\n' 'package bootstrap' '#SliceLowerInput: {v:int}' > incomplete.cue
eval_success "$PWD/incomplete.cue" "$root"
expect_failure incomplete-isolated 'incomplete value' cue export "$PWD/incomplete.cue" "$root"
clean_json backfilled.json cue export "$schema" "$fragment" "$PWD/incomplete.cue" "$one"
cmp expected-1.json backfilled.json

# Test fail-stop under conditional invocation (errexit suppressed) using BOTH
# actual production branches; no schema/context CUE call may precede rejection.
gate_failure() {
  local label=$1 fixture=$2 data=$3 raw=$4 status=0
  rm -f composition-entered
  : > "$TRACE"
  compose "$fixture" "$data" "$raw" "$one" forward > "$label.out" 2> "$label.err" || status=$?
  test "$status" -ne 0 && test ! -s "$label.out" && test -s "$label.err"
  test ! -e composition-entered
  if grep -F "$schema" "$TRACE"; then return 1; fi
  if grep -F "$fragment" "$TRACE"; then return 1; fi
  if grep -F "$one" "$TRACE"; then return 1; fi
  cp "$TRACE" "$OUT/receipts/$label-argv"
  printf '%s\t%s\tgate-before-composition\n' "$label" "$status" >> "$OUT/receipts/categories"
}
for defect in missing incomplete string bool null fraction decimal exponent extra outside negative; do
  case "$defect" in
    missing) json='{}'; body='{}' ;;
    incomplete) json='{}'; body='{v:int}' ;;
    string) json='{"v":"0"}'; body='{v:"0"}' ;;
    bool) json='{"v":false}'; body='{v:false}' ;;
    null) json='{"v":null}'; body='{v:null}' ;;
    fraction) json='{"v":0.5}'; body='{v:0.5}' ;;
    decimal) json='{"v":1.0}'; body='{v:1.0}' ;;
    exponent) json='{"v":1e0}'; body='{v:1e0}' ;;
    extra) json='{"v":0,"extra":true}'; body='{v:0,extra:true}' ;;
    outside) json='{"v":2}'; body='{v:2}' ;;
    negative) json='{"v":-1}'; body='{v:-1}' ;;
  esac
  printf '%s\n' "$json" > invalid.json
  printf '%s\n' 'package bootstrap' "#SliceLowerInput: $body" > invalid.cue
  gate_failure "gate-selected-$defect" slice-control "$PWD/invalid.json" "$owner"
  gate_failure "gate-raw-$defect" tests/valid/slice-control-lower-one "$NATIVE_JSON" "$PWD/invalid.cue"
done
printf '%s\n' 'package bootstrap' > absent.cue
gate_failure gate-absent-definition tests/valid/slice-control-lower-one "$NATIVE_JSON" "$PWD/absent.cue"
gate_failure gate-absent-file tests/valid/slice-control-lower-one "$NATIVE_JSON" "$PWD/nonexistent.cue"
gate_failure gate-absent-json slice-control "$PWD/nonexistent.json" "$owner"
# Closed helper definition rejects extra-field refinement after successful import.
slice_lower_provider slice-control "$NATIVE_JSON" "$owner"
printf '%s\n' 'package bootstrap' '#SliceLowerInput & {extra:true}' > extra-context.cue
expect_failure closed-extra 'field not allowed' cue export "$slice_provider" "$PWD/extra-context.cue"

# Genuine source effect: no expected bytes are ever construction inputs.
IFS= read -r -d '' text < "$owner" || [[ -n $text ]]
needle='*0 | 1'
[[ $text = *"$needle"* ]]
rest=${text#*"$needle"}
[[ $rest != *"$needle"* ]]
printf '%s' "${text/"$needle"/'*1 | 0'}" > mutated-owner.cue
for order in forward reverse; do
  files=("$PWD/mutated-owner.cue" "$root")
  if [[ $order = reverse ]]; then files=("$root" "$PWD/mutated-owner.cue"); fi
  clean_json "mutated-helper-$order.json" native "${files[@]}"
  printf '{"v":1}\n' | jq -S . > expected-mutated-helper.json
  cmp expected-mutated-helper.json "mutated-helper-$order.json"
  clean_json "mutated-go-helper-$order.json" cue export "${files[@]}"
  cmp "mutated-helper-$order.json" "mutated-go-helper-$order.json"
  clean_json "mutated-selected-$order.json" compose slice-control "$PWD/mutated-helper-$order.json" "$PWD/mutated-owner.cue" "$canonical" "$order"
  clean_json "mutated-raw-$order.json" compose tests/valid/slice-control-tail "$NATIVE_JSON" "$PWD/mutated-owner.cue" "$canonical" "$order"
  for route in selected raw; do
    cmp expected-1.json "mutated-$route-$order.json"
    generate "mutated-$route-$order.json" > "mutated-$route-$order.rs"
    cmp expected-1.rs "mutated-$route-$order.rs"
  done
done
# Restore an original canonical route after all failures/mutations; no stale value.
clean_json restored.json compose slice-control "$NATIVE_JSON" "$owner" "$canonical" forward
cmp expected-0.json restored.json
cp inverse.sha256 unchanged.sha256 "$OUT/receipts/"
printf '%s\n' 'Focused source/consumer proof passed; closure, runtime tests, sandbox rebuilds and full preflight are separate obligations.' > "$OUT/receipts/result"
